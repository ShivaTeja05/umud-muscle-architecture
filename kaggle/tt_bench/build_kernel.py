"""Generate the TT-BENCH Kaggle kernels (kernel.py + kernel-metadata.json per folder).

kernel.py embeds (zlib + base64) three sources, unchanged:
  apo_fix_src.py  = kaggle/apo_v2_fix/ext/infer_fix_ext.py   (apo_v2fix model, BN fix, letterbox, NpzWriter)
  fo_src.py       = kaggle/fasc_orient_v1/train.py           (fasc_orient_v1 model, viewport, TTA forward, NpzZip)
  tt_stages.py    = kaggle/tt_bench/tt_stages.py             (the TT data / inference stages)
and runs the configured stages in separate subprocesses (CPU kernels; no GPU).

  python kaggle/tt_bench/build_kernel.py            -> cpusmoke/, apo/, orient/ (and extra/ as an unpushed template)
GPL-3.0-only.
"""
from __future__ import annotations

import base64
import json
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
SOURCES = {"apo_fix_src.py": REPO / "kaggle/apo_v2_fix/ext/infer_fix_ext.py",
           "fo_src.py": REPO / "kaggle/fasc_orient_v1/train.py",
           "tt_stages.py": HERE / "tt_stages.py"}
COMP = "umud-challenge-muscle-architecture-in-ultrasound-data"
BASE_SOURCES = ["shivateja005/umud-apo-v2", "shivateja005/umud-fasc-orient-v1",
                "shivateja005/umud-u-net-aponeurosis-384-cli", "shivateja005/umud-u-net-fascicle-384-cli"]
KERNELS = {
    "cpusmoke": dict(slug="umud-tt-bench-cpusmoke", title="UMUD TT Bench Cpusmoke", smoke=2,
                     stages=["data", "apo", "ours", "orient"], extra=None, sources=BASE_SOURCES),
    "apo": dict(slug="umud-tt-bench-apo", title="UMUD TT Bench Apo", smoke=0, stages=["data", "apo", "ours"],
                extra=None, sources=BASE_SOURCES),
    "orient": dict(slug="umud-tt-bench-orient", title="UMUD TT Bench Orient", smoke=0, stages=["data", "orient"],
                   extra=None, sources=BASE_SOURCES),
    # second pass for the v16 insfield model once its run has finished (not pushed by default)
    "extra": dict(slug="umud-tt-bench-extra", title="UMUD TT Bench Extra", smoke=0, stages=["data", "extra"],
                  extra={"tag": "fasc_ins_v16", "path_contains": "umud-v16-insfield-a", "n_out": 6, "size": 512,
                         "encoder": "tu-convnext_small.fb_in22k_ft_in1k"},
                  sources=BASE_SOURCES + ["shivateja005/umud-v16-insfield-a"]),
}

LAUNCHER = '''"""UMUD TT-BENCH launcher (generated by kaggle/tt_bench/build_kernel.py). GPL-3.0-only."""
import base64, json, os, subprocess, sys, time, zlib
from pathlib import Path

SMOKE = {smoke}
STAGES = {stages}
EXTRA = {extra}
SOURCES = {payload}
TMP = Path("/tmp/tt")
OUT = Path("/kaggle/working/tt_out")
T0 = time.time()


def say(msg):
    print(f"[launcher {{time.time() - T0:7.1f}}s] {{msg}}", flush=True)


def run(stage):
    env = dict(os.environ, TT_SMOKE=str(SMOKE), PYTHONUNBUFFERED="1")
    if EXTRA:
        env["TT_EXTRA"] = json.dumps(EXTRA)
    (OUT / "logs").mkdir(parents=True, exist_ok=True)
    t = time.time()
    with (OUT / "logs" / f"{{stage}}.log").open("w", encoding="utf-8") as lf:
        p = subprocess.Popen([sys.executable, "-u", str(TMP / "tt_stages.py"), "--stage", stage], cwd=str(TMP),
                             stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, env=env)
        for line in p.stdout:
            print(f"[{{stage}}] {{line}}", end="", flush=True)
            lf.write(line)
        code = p.wait()
    say(f"stage {{stage}} exit={{code}} {{time.time() - t:.0f}}s")
    return code


def main():
    TMP.mkdir(parents=True, exist_ok=True)
    OUT.mkdir(parents=True, exist_ok=True)
    for name, blob in SOURCES.items():
        (TMP / name).write_text(zlib.decompress(base64.b64decode(blob)).decode("utf-8"), encoding="utf-8")
    say(f"python={{sys.version.split()[0]}} cpus={{os.cpu_count()}} smoke={{SMOKE}} stages={{STAGES}}")
    codes = {{}}
    for st in STAGES:
        codes[st] = run(st)
        if st == "data" and codes[st] != 0:
            break
    (OUT / "exit_codes.json").write_text(json.dumps(codes))
    say(f"exit codes {{codes}}")
    for p in sorted((OUT / "maskbank").glob("*")) if (OUT / "maskbank").exists() else []:
        say(f"  {{p.name}} {{p.stat().st_size / 1e6:.2f}} MB")


main()
'''


def main() -> None:
    payload = {name: base64.b64encode(zlib.compress(p.read_text(encoding="utf-8").encode("utf-8"), 9)).decode("ascii")
               for name, p in SOURCES.items()}
    for folder, k in KERNELS.items():
        d = HERE / folder
        d.mkdir(exist_ok=True)
        (d / "kernel.py").write_text(LAUNCHER.format(smoke=k["smoke"], stages=repr(k["stages"]), extra=repr(k["extra"]),
                                                     payload=json.dumps(payload, indent=0)), encoding="utf-8")
        meta = {"id": f"shivateja005/{k['slug']}", "title": k["title"], "code_file": "kernel.py", "language": "python",
                "kernel_type": "script", "is_private": "true", "enable_gpu": "false", "enable_tpu": "false",
                "enable_internet": "true", "competition_sources": [COMP], "dataset_sources": [],
                "kernel_sources": k["sources"], "model_sources": []}
        (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {d.name}/kernel.py ({(d / 'kernel.py').stat().st_size / 1e3:.0f} kB) stages={k['stages']}")


if __name__ == "__main__":
    main()
