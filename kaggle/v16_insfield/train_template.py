def to_input(img_u8, torch):
    x = img_u8.float().unsqueeze(1) * (1.0 / 255.0)
    mean = torch.tensor(IMAGENET_MEAN, device=x.device).view(1, 3, 1, 1)
    std = torch.tensor(IMAGENET_STD, device=x.device).view(1, 3, 1, 1)
    return ((x.expand(-1, 3, -1, -1) - mean) / std).contiguous(memory_format=torch.channels_last)


def forward_maps(model, x, torch, tta: bool):
    """-> prob, cos2, sin2, line prob, insertion PA (deg), log(FL/MT)  (B,H,W) float32; hflip flips the sin2 sign."""
    b = x.shape[0]
    xin = torch.cat([x, torch.flip(x, dims=[3])], 0) if tta else x
    with amp_ctx(torch):
        out = model(xin).float()

    def heads(o, mirror: bool):
        s = torch.tanh(o[:, 2])
        return [torch.sigmoid(o[:, 0]), torch.tanh(o[:, 1]), -s if mirror else s, torch.sigmoid(o[:, 3]),
                o[:, 4] * PA_SCALE, o[:, 5]]

    hs = heads(out[:b], False)
    if tta:
        hf = heads(torch.flip(out[b:], dims=[3]), True)
        hs = [0.5 * (u + v) for u, v in zip(hs, hf)]
    return hs


class TrainSet:
    def __init__(self, items: list[dict], augment: bool) -> None:
        self.items = items
        self.augment = augment

    def __len__(self) -> int:
        return len(self.items)

    def __getitem__(self, idx: int):
        import torch

        it = self.items[idx % len(self.items)]
        seed = (torch.initial_seed() + idx * 7919) % (2**32)
