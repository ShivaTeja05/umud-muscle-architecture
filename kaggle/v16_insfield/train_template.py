def _xform(segs: np.ndarray, off: np.ndarray, m: np.ndarray) -> np.ndarray:
    if not len(segs):
        return np.zeros((0, 4))
    s = segs - np.array([off[0], off[1], off[0], off[1]], np.float32)
    p1 = (m[:2, :2] @ s[:, :2].T + m[:2, 2:3]).T
    p2 = (m[:2, :2] @ s[:, 2:].T + m[:2, 2:3]).T
    return np.concatenate([p1, p2], 1)


def make_sample(it: dict, rng: np.random.Generator | None) -> dict:
    """fasc_orient_v1 make_sample for both item kinds; every sample carries every key (default collate)."""
    crop = it["crop"]
    vl = it.get("kind") == "vl"
    h, w = crop.shape
    x0, y0, ww, hh = 0, 0, w, h
    if rng is not None:
        if rng.random() < 0.35:  # narrow field of view (e.g. Philips Lumify)
            ww = max(32, int(round(rng.uniform(0.3, 1.0) * w)))
            x0 = int(rng.integers(0, w - ww + 1))
        if rng.random() < 0.15:
            hh = max(32, int(round(rng.uniform(0.65, 1.0) * h)))
            y0 = int(rng.integers(0, h - hh + 1))
    sub = crop[y0:y0 + hh, x0:x0 + ww]
    m = letterbox_matrix(ww, hh)
    if rng is not None:
        m = aug_matrix(rng, aniso=not vl) @ m
    img = warp_image(sub, m)
    valid = _poly_mask(m, ww, hh)
    off = np.array([x0, y0], np.float32)
    if vl:
        tg = _empty_comp_targets()
        tg.update(render_vl_targets(_xform(it["pieces"], off, m), it["attrs"], valid))
    else:
        tg = render_targets(_xform(it["segs"], off, m), valid)
        tg.update(_empty_vl_targets())
    if rng is not None:
        img = intensity_aug(img, valid, rng)
    tg["img"] = img
    tg["valid"] = valid
    tg["isvl"] = np.array([1 if vl else 0], np.uint8)
    return tg


