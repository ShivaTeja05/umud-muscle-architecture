def render_vl_targets(pieces: np.ndarray, attrs: np.ndarray, valid: np.ndarray) -> dict:
    """pieces (K,4) canvas segments of the expert polylines (+ extrapolations); attrs (K,5) = u (0 sup .. 1 deep,
    piece centre), ext flag, track PA (deg), track log(FL/MT), track index -> VL orientation / line / dense targets."""
    from scipy import ndimage

    line = np.zeros((SIZE, SIZE), np.uint8)
    idm = np.zeros((SIZE, SIZE), np.uint16)
    k = len(pieces)
    ctab = np.zeros(k + 1, np.float32)
    stab = np.zeros(k + 1, np.float32)
    okt = np.zeros(k + 1, bool)
    for i, (x1, y1, x2, y2) in enumerate(pieces):
        if not (np.isfinite([x1, y1, x2, y2]).all()) or max(abs(x1), abs(y1), abs(x2), abs(y2)) > 50 * SIZE:
            continue
        p1 = (int(round(x1 * 16)), int(round(y1 * 16)))
        p2 = (int(round(x2 * 16)), int(round(y2 * 16)))
        cv2.line(line, p1, p2, 1, SEG_WIDTH, cv2.LINE_8, 4)
        cv2.line(idm, p1, p2, i + 1, 1, cv2.LINE_8, 4)
        dx, dy = x2 - x1, y2 - y1
        l2 = dx * dx + dy * dy
        if l2 >= 1.0:
            ctab[i + 1] = (dx * dx - dy * dy) / l2
            stab[i + 1] = 2.0 * dx * dy / l2
            okt[i + 1] = True
    line &= valid
    z16 = np.zeros((SIZE, SIZE), np.float16)
    out = {"line": line, "vw": z16, "vcos2": z16, "vsin2": z16, "pat": z16, "flt": z16,
           "ut": np.full((SIZE, SIZE), -1, np.float16), "tid": np.zeros((SIZE, SIZE), np.uint8),
           "vext": np.zeros((SIZE, SIZE), np.uint8)}
    if not (idm > 0).any():
        return out
    dist, ind = ndimage.distance_transform_edt(idm == 0, return_indices=True)
    nid = idm[ind[0], ind[1]]
    om = (dist <= VL_ORI_RADIUS * SIZE / 512.0) & okt[nid] & (valid > 0)
    a = np.vstack([np.zeros((1, attrs.shape[1]), np.float32), attrs.astype(np.float32)])[nid]
    u, ext = a[..., 0], a[..., 1] > 0.5
    w = (1.0 + DEEP_BOOST * (u >= DEEP_U)) * np.where(ext, EXT_W, 1.0)
    out.update(
        vw=np.where(om, w, 0.0).astype(np.float16),
        vcos2=np.where(om, ctab[nid], 0.0).astype(np.float16),
        vsin2=np.where(om, stab[nid], 0.0).astype(np.float16),
        pat=np.where(om, a[..., 2] / PA_SCALE, 0.0).astype(np.float16),
        flt=np.where(om, a[..., 3], 0.0).astype(np.float16),
        ut=np.where(om, u, -1.0).astype(np.float16),
        tid=np.where(om, a[..., 4] + 1, 0).astype(np.uint8),
        vext=(om & ext).astype(np.uint8),
    )
    return out


