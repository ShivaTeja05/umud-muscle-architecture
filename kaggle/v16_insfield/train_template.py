def apply_reference_folds(items: list[dict], alias_rows: list[list], stats: dict) -> list[list]:
    """Overwrite the recomputed competition folds with the fasc_orient_v1 folds (embedded csv) -> same splits as
    the control model. Items missing from the reference keep their recomputed fold (logged)."""
    ref = {}
    path = SRC / "fasc_folds.csv"
    if path.exists():
        with open(path) as fh:
            for r in csv.DictReader(fh):
                ref[r["stem"]] = (int(r["group"]), int(r["fold"]))
    hit = [it["stem"] in ref for it in items]
    n_agree = sum(it["fold"] == ref[it["stem"]][1] for it, h in zip(items, hit) if h)
    for it, h in zip(items, hit):
        if h:
            it["group"], it["fold"] = ref[it["stem"]]
    stats.update(folds_source=str(path), folds_ref_hits=int(sum(hit)), folds_ref_missing=int(len(items) - sum(hit)),
                 folds_recomputed_agree=int(n_agree))
    rows = []
