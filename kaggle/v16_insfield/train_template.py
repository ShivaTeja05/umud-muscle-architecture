def _per_sample_bce(torch, logit, target, pos_w):
    return torch.nn.functional.binary_cross_entropy_with_logits(logit, target, pos_weight=pos_w,
                                                                reduction="none").mean((1, 2))


def train_fold(fold: int, gpu_state: dict, torch) -> None:
    from torch.utils.data import DataLoader

    rng = np.random.default_rng(SEED + fold)
    tr = [it for it in ITEMS if it["fold"] != fold]
    va = [it for it in ITEMS if it["fold"] == fold]
    vtr = [it for it in VL_ITEMS if it["fold"] != fold] if VL_ON else []
    vva = [it for it in VL_ITEMS if it["fold"] == fold]
    if SMOKE:
        tr = [tr[i] for i in rng.choice(len(tr), min(SMOKE_TRAIN, len(tr)), replace=False)]
        va = [va[i] for i in rng.choice(len(va), min(SMOKE_VAL, len(va)), replace=False)]
        vtr, vva = vtr[:SMOKE_VL], vva[:SMOKE_VAL]
    torch.manual_seed(SEED + fold)
    train_list = tr + vtr * VL_REPEAT
    n_cpu = os.cpu_count() or 4
    n_workers = 0 if DEV.type == "cpu" else max(2, min(4, n_cpu // gpu_state["n_parallel"] + 1))
    ds = TrainSet(train_list, augment=True)
    dl_kw = dict(batch_size=BATCH, shuffle=True, num_workers=n_workers, pin_memory=DEV.type == "cuda",
                 drop_last=True)
    if n_workers:
        dl_kw.update(persistent_workers=True, worker_init_fn=_worker_init, prefetch_factor=4)
    dl = DataLoader(ds, **dl_kw)
    t_cache = time.time()
    cache = build_val_cache(va, torch)
    vcache = build_val_cache(vva, torch) if vva else []
    log(f"fold {fold}: train comp={len(tr)} vl={len(vtr)}x{VL_REPEAT} | val comp={len(va)} vl={len(vva)} "
        f"workers={n_workers} steps/epoch={len(dl)} val_cache={time.time() - t_cache:.1f}s")

    model = build_model(pretrained=True).to(DEV).to(memory_format=torch.channels_last)
    enc_params = list(model.encoder.parameters())
    enc_ids = {id(p) for p in enc_params}
    dec_params = [p for p in model.parameters() if id(p) not in enc_ids]
    opt = torch.optim.AdamW([{"params": enc_params, "lr": LR_ENC}, {"params": dec_params, "lr": LR_DEC}],
                            weight_decay=WEIGHT_DECAY)
    steps = len(dl) if MAX_STEPS is None else min(len(dl), MAX_STEPS)
    warm = max(1, int(steps * WARMUP_EPOCHS))
    n_epochs = gpu_state.get("n_epochs", MAX_EPOCHS)
    if "ep_time" in gpu_state:
        folds_left = max(1, gpu_state["plan_folds"] - gpu_state["done"])
        n_fit = int((T0 + TRAIN_BUDGET_S - time.time()) / folds_left / (gpu_state["ep_time"] * 1.03))
        n_epochs = int(max(MIN_EPOCHS, min(n_epochs, n_fit)))
        log(f"fold {fold}: n_epochs={n_epochs} (budget fit {n_fit})")
    sched_state = {"total": n_epochs * steps}

    def lr_lambda(step: int) -> float:
        if step < warm:
            return 0.05 + 0.95 * step / warm
        total = max(sched_state["total"], warm + 1)
        prog = min(1.0, (step - warm) / (total - warm))
        return LR_FLOOR + (1 - LR_FLOOR) * 0.5 * (1 + math.cos(math.pi * prog))

    sched = torch.optim.lr_scheduler.LambdaLR(opt, lr_lambda)
    scaler = torch.amp.GradScaler("cuda", enabled=DEV.type == "cuda")
    pos_w = torch.tensor([POS_WEIGHT], device=DEV)
    hist_path = METRIC_DIR / f"history_fold{fold}.csv"
    cols = ["epoch", "loss", "bce", "dice_l", "skel_l", "ori_l", "vori_l", "line_l", "pa_l", "flr_l", "dice50",
            "ang_mae", "med_err", "vl_mid_med_err", "vl_deep_med_err", "vl_pa_field_mae", "vl_pa_field_bias",
            "vl_pa_head_mae", "vl_flrel_head_mae", "sel", "lr", "sec"]
    with open(hist_path, "w", newline="") as fh:
        csv.writer(fh).writerow(cols)
    best, best_sel, best_epoch = None, float("inf"), 0
    ckpt_path = CKPT_DIR / f"fold{fold}.pt"
    epoch = 0
    while epoch < n_epochs:
        epoch += 1
        model.train()
        t_ep = time.time()
        sums = np.zeros(9)
        nb = 0
        for step, b in enumerate(dl, 1):
            x = to_input(b["img"].to(DEV, non_blocking=True), torch)
            isvl = b["isvl"].to(DEV).float().view(-1)
            comp = 1.0 - isvl
            seg_t = b["seg"].to(DEV, non_blocking=True).float()
            skel = b["skel"].to(DEV, non_blocking=True).float()
            om = b["om"].to(DEV, non_blocking=True).float()
            ct = b["cos2"].to(DEV, non_blocking=True).float()
            st = b["sin2"].to(DEV, non_blocking=True).float()
            vw = b["vw"].to(DEV, non_blocking=True).float()
            vct = b["vcos2"].to(DEV, non_blocking=True).float()
            vst = b["vsin2"].to(DEV, non_blocking=True).float()
            line_t = b["line"].to(DEV, non_blocking=True).float()
            valid = b["valid"].to(DEV, non_blocking=True).float()
            pat = b["pat"].to(DEV, non_blocking=True).float()
            flt = b["flt"].to(DEV, non_blocking=True).float()
            with amp_ctx(torch):
                out = model(x)
            out = out.float()
            logit = out[:, 0]
            ncomp = comp.sum().clamp_min(1.0)
            bce = (_per_sample_bce(torch, logit, seg_t, pos_w) * comp).sum() / ncomp
            p = torch.sigmoid(logit)
            inter = (p * seg_t).sum((1, 2))
            dice_i = 1 - (2 * inter + 1) / (p.sum((1, 2)) + seg_t.sum((1, 2)) + 1)
            dice_l = (dice_i * comp).sum() / ncomp
            sk_n = skel.sum((1, 2))
            has = (sk_n > 0) & (comp > 0)
            skel_l = (1 - (p * skel).sum((1, 2))[has] / sk_n[has]).mean() if bool(has.any()) else logit.sum() * 0
            cp, sp = torch.tanh(out[:, 1]), torch.tanh(out[:, 2])
            omc = om * comp.view(-1, 1, 1)
            ori_l = (((cp - ct).abs() + (sp - st).abs()) * omc).sum() / (2 * omc.sum().clamp_min(1))
            vwv = vw * isvl.view(-1, 1, 1)
            vori_l = (((cp - vct).abs() + (sp - vst).abs()) * vwv).sum() / (2 * vwv.sum().clamp_min(1))
            vmask = (vwv > 0).float()
            if bool((isvl > 0).any()):
                lv = valid * isvl.view(-1, 1, 1)
                line_l = (torch.nn.functional.binary_cross_entropy_with_logits(
                    out[:, 3], line_t, pos_weight=pos_w, reduction="none") * lv).sum() / lv.sum().clamp_min(1)
                pa_l = (torch.nn.functional.smooth_l1_loss(out[:, 4], pat, reduction="none", beta=0.05)
                        * vmask).sum() / vmask.sum().clamp_min(1)
                flr_l = (torch.nn.functional.smooth_l1_loss(out[:, 5], flt, reduction="none", beta=0.05)
                         * vmask).sum() / vmask.sum().clamp_min(1)
            else:
                line_l = pa_l = flr_l = out.sum() * 0
            loss = (W_BCE * bce + W_DICE * dice_l + W_SKEL * skel_l + W_ORI * ori_l + W_VLORI * vori_l
                    + W_LINE * line_l + W_PA * pa_l + W_FLR * flr_l)
            opt.zero_grad(set_to_none=True)
            scaler.scale(loss).backward()
            scaler.unscale_(opt)
            torch.nn.utils.clip_grad_norm_(model.parameters(), 2.0)
            scaler.step(opt)
            scaler.update()
            sched.step()
            sums += [float(v.detach()) for v in (loss, bce, dice_l, skel_l, ori_l, vori_l, line_l, pa_l, flr_l)]
            nb += 1
            if step % 50 == 0 or SMOKE:
                el = time.time() - t_ep
                log(f"fold {fold} ep {epoch} step {step}/{steps} loss={sums[0] / nb:.4f} ori={sums[4] / nb:.4f} "
                    f"vori={sums[5] / nb:.4f} pa={sums[7] / nb:.4f} ms/step={1000 * el / step:.0f}")
            if MAX_STEPS is not None and step >= MAX_STEPS:
                break
        t_train = time.time() - t_ep
        mc = evaluate_comp(model, cache, torch)
        mv = evaluate_vl(model, vcache, torch) if vcache else {}
        sel = sel_score(mc, mv)
        sec = time.time() - t_ep
        lr_now = opt.param_groups[0]["lr"]
        sums /= max(1, nb)
        log(f"EPOCH fold={fold} ep={epoch}/{n_epochs} loss={sums[0]:.4f} ori={sums[4]:.4f} vori={sums[5]:.4f} | "
            f"comp dice50={mc['dice50']:.4f} ang_mae={mc['ang_mae']:.2f} | VL mid={mv.get('vl_mid_med_err', float('nan')):.2f} "
            f"deep={mv.get('vl_deep_med_err', float('nan')):.2f} paF={mv.get('vl_pa_field_mae', float('nan')):.2f}"
            f"({mv.get('vl_pa_field_bias', float('nan')):+.2f}) paH={mv.get('vl_pa_head_mae', float('nan')):.2f} "
            f"sel={sel:.3f} | lr={lr_now:.2e} train={t_train:.0f}s total={sec:.0f}s")
        with open(hist_path, "a", newline="") as fh:
            csv.writer(fh).writerow([epoch, *[round(float(v), 5) for v in sums], mc["dice50"], mc["ang_mae"],
                                     mc["med_err"], *[mv.get(k, float("nan")) for k in (
                                         "vl_mid_med_err", "vl_deep_med_err", "vl_pa_field_mae", "vl_pa_field_bias",
                                         "vl_pa_head_mae", "vl_flrel_head_mae")], sel, lr_now, sec])
        if not np.isfinite(sel):
            sel = 1e6
        if best is None or sel < best_sel - 1e-4:
            best, best_sel, best_epoch = {**mc, **mv, "sel": sel}, sel, epoch
            sd = {k: (v.half() if v.is_floating_point() else v) for k, v in model.state_dict().items()}
            torch.save({"state_dict": sd, "epoch": epoch, "metrics": best, "fold": fold, "encoder": ENCODER,
                        "size": SIZE, "classes": ALL_CHANNELS}, ckpt_path)
            log(f"fold {fold}: saved best epoch {epoch} sel={sel:.3f}")
        if epoch == 1 and "n_epochs" not in gpu_state and not SMOKE:
            ep_time = sec
            left = T0 + TRAIN_BUDGET_S - time.time() + ep_time
            per_fold = left / gpu_state["plan_folds"]
            n_epochs = int(max(MIN_EPOCHS, min(MAX_EPOCHS, per_fold // (ep_time * 1.03))))
            gpu_state["n_epochs"] = n_epochs
            gpu_state["ep_time"] = ep_time
            sched_state["total"] = n_epochs * steps
            log(f"fold {fold}: epoch time {ep_time:.0f}s -> n_epochs={n_epochs} for all folds on this GPU")
        if time.time() > T0 + HARD_TRAIN_END_S:
            log(f"fold {fold}: HARD time limit reached after epoch {epoch}; stopping this fold")
            break
    del dl
    log(f"fold {fold}: best epoch {best_epoch} {json.dumps(best, default=float)}")

    # ---- best checkpoint: TTA metrics, then OOF maps (competition val fold AND the VL val subjects)
    state = torch.load(ckpt_path, map_location="cpu", weights_only=False)
    model.load_state_dict({k: v.float() if v.is_floating_point() else v for k, v in state["state_dict"].items()})
    model = model.to(DEV).to(memory_format=torch.channels_last).eval()
    mc_tta = evaluate_comp(model, cache, torch, tta=True)
    mv_tta = evaluate_vl(model, vcache, torch, tta=True) if vcache else {}
    log(f"fold {fold}: TTA comp ang_mae={mc_tta['ang_mae']:.2f} | VL bins={np.round(mv_tta.get('vl_bin_median_err', []), 2).tolist()} "
        f"paF={mv_tta.get('vl_pa_field_mae', float('nan')):.2f}")
    t_oof = time.time()
    rows = []
    for kind, lst in (("train_oof", va), ("vl", vva)):
        writers = {ch: NpzZip(OOF_PART_DIR / f"fold{fold}_{kind}_{ch}.npz", level=6) for ch in ALL_CHANNELS}
        for j, it in enumerate(lst):
            gray = it.get("gray")
            if gray is None:
                gray = np.zeros((it["H"], it["W"]), np.uint8)
                x1, y1, x2, y2 = it["box"]
                gray[y1:y2, x1:x2] = it["crop"]
            enc, _ = predict_native([model], gray, it["box"], torch)
            for ch in ALL_CHANNELS:
                writers[ch].add(it["stem"], enc[ch])
            rows.append([kind, it["stem"], it["name"], it["H"], it["W"]])
            if j < 2:
                save_viz(VIZ_DIR / f"oof_fold{fold}_{kind}_{it['stem']}.jpg", gray, enc, it.get("viz_lines"))
        for w in writers.values():
            w.close()
    with open(OOF_PART_DIR / f"fold{fold}_manifest.csv", "w", newline="") as fh:
        csv.writer(fh).writerows(rows)
    res = {"fold": fold, "best_epoch": best_epoch, "n_epochs": n_epochs, "best": best, "tta_comp": mc_tta,
           "tta_vl": mv_tta, "n_train": len(tr), "n_vl_train": len(vtr), "n_val": len(va), "n_vl_val": len(vva),
           "oof_seconds": time.time() - t_oof}
    (METRIC_DIR / f"fold{fold}.json").write_text(json.dumps(res, indent=2, default=float))
    del model, opt, cache, vcache
    if DEV.type == "cuda":
        torch.cuda.empty_cache()


def gpu_worker(gpu: int, folds: list[int], plan_folds: int, n_parallel: int) -> None:
    global _LOG_PREFIX, _LOG_FILE, DEV
    os.environ["CUDA_VISIBLE_DEVICES"] = str(gpu)
    _LOG_PREFIX = f"[gpu{gpu}]"
    _LOG_FILE = LOG_DIR / f"gpu{gpu}.log"
    code = 0
    try:
        import torch

        DEV = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        torch.backends.cudnn.benchmark = True
        torch.set_num_threads(1)
        cv2.setNumThreads(1)
        log(f"worker start folds={folds} device={torch.cuda.get_device_name(0) if DEV.type == 'cuda' else 'cpu'}")
        state = {"plan_folds": plan_folds, "n_parallel": n_parallel, "done": 0}
        for k in folds:
            try:
                train_fold(k, state, torch)
            except Exception:  # noqa: BLE001
                code = 1
                log(f"fold {k} FAILED:\n{traceback.format_exc()}")
            state["done"] += 1
    except BaseException:  # noqa: BLE001
        code = 2
        log(f"worker FAILED:\n{traceback.format_exc()}")
    os._exit(code)


