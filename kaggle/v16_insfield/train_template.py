def run_inference(models, datasets: dict, manifest_rows: list, vp_rows: list, torch) -> None:
    for name in ("test", "static", "dynamic"):
        entries = datasets.get(name) or []
        if CPU_SMOKE and name != "test":
            entries = entries[:2]
        if not entries:
            continue
        t = time.time()
        writers = {ch: NpzZip(MASKBANK / f"{name}__{MODEL_NAME}_{ch}.npz") for ch in ALL_CHANNELS}
        n_ok = 0
        for j, (key, path, src) in enumerate(entries):
            try:
                gray = read_gray(path)
                if max(gray.shape) > 4000 or min(gray.shape) < 64:
                    log(f"skip {name}/{src}: shape {gray.shape}")
                    continue
                box, kind = viewport(gray, path.suffix.lower())
                enc, _ = predict_native(models, gray, box, torch)
                for ch in ALL_CHANNELS:
                    writers[ch].add(key, enc[ch])
                manifest_rows.append([name, key, src, gray.shape[0], gray.shape[1]])
                vp_rows.append([name, key, kind, *box])
                n_ok += 1
                if j < (4 if name == "test" else 2) or (name == "test" and j % 60 == 0):
                    save_viz(VIZ_DIR / f"{name}_{key}.jpg", gray, enc)
            except Exception:  # noqa: BLE001
                log(f"inference failed {name}/{src}:\n{traceback.format_exc()}")
        for w in writers.values():
            w.close()
        log(f"inference {name}: {n_ok}/{len(entries)} images in {time.time() - t:.0f}s")


def main() -> None:
    global ITEMS, VL_ITEMS, _LOG_FILE, DEV
    for d in (MASKBANK, CKPT_DIR, LOG_DIR, METRIC_DIR, VIZ_DIR, OOF_PART_DIR, TMP / "ext"):
        d.mkdir(parents=True, exist_ok=True)
    _LOG_FILE = LOG_DIR / "main.log"
    log(f"MODE={MODE} model={MODEL_NAME} encoder={ENCODER} size={SIZE} VL_ON={VL_ON} VL_REPEAT={VL_REPEAT} "
        f"note={NOTE!r} python={sys.version.split()[0]} cpu={os.cpu_count()}")
    log("nvidia-smi: " + sh("nvidia-smi -L").strip().replace("\n", " | "))
    import torch

    torch.set_num_threads(1)
    smp = ensure_smp()
    import timm

    log(f"torch={torch.__version__} smp={smp.__version__} timm={timm.__version__} cv2={cv2.__version__}")
    image_dir = find_dir("fasc_images_new_model_v1")
    mask_dir = find_dir("fasc_masks_new_model_v1")
    test_dir = find_dir("test_set_v2")
    pairs = find_pairs(image_dir, mask_dir)
    if CPU_SMOKE:
        pairs = pairs[:SMOKE_PAIRS]
    log(f"found {len(pairs)} fascicle pairs; test dir {test_dir}")
    items, _, stats = prepare_items(pairs)
    alias_rows = apply_reference_folds(items, [], stats)
    ITEMS = items
    with open(METRIC_DIR / "folds.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["stem", "representative", "group", "fold"])
        w.writerows(alias_rows)

    # VL first (needed for training); static / dynamic are fetched while the GPUs train
    datasets: dict[str, list[tuple[str, Path, str]]] = {}
    vl_files = gather_extra("vl")  # also for the control arm: its VL metrics are the in-kernel baseline
    datasets["vl_all"] = vl_files
    comp_thumbs = np.stack([thumbnail(it["crop"]) for it in items]) if items else None
    VL_ITEMS, vst = vl_items_from_payload(vl_files, comp_thumbs)
    del comp_thumbs
    stats.update(vst)
    log("data stats: " + json.dumps(stats, default=str))
    (METRIC_DIR / "data_stats.json").write_text(json.dumps(stats, indent=2, default=str))
    if VL_ON and not VL_ITEMS:
        raise RuntimeError("no VL expert-line items (download / path matching failed)")
    with open(METRIC_DIR / "vl_folds.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["image_id", "key", "subject", "fold", "near_dup_comp"])
        w.writerows([[it["stem"], it["key"], it["subject"], it["fold"], int(it["near_dup_comp"])] for it in VL_ITEMS])

    t = time.time()
    _m = build_model(pretrained=True)
    n_params = sum(p.numel() for p in _m.parameters())
    del _m
    log(f"pretrained {ENCODER} cached ({n_params / 1e6:.1f}M params, {time.time() - t:.0f}s)")

    n_gpu = sh("nvidia-smi -L").count("GPU ")
    test_files = sorted([p for p in test_dir.rglob("*") if p.suffix.lower() in IMAGE_SUFFIXES], key=lambda p: p.name)
    datasets["test"] = [(p.stem, p, p.name) for p in test_files][:TEST_LIMIT]
    if n_gpu == 0:  # CPU smoke: train in-process (no fork after OpenMP use)
        DEV = torch.device("cpu")
        torch.set_num_threads(4)
        state = {"plan_folds": len(TRAIN_FOLDS), "n_parallel": 1, "done": 0}
        for k in TRAIN_FOLDS:
            train_fold(k, state, torch)
            state["done"] += 1
        for name in ("static", "dynamic"):
            try:
                datasets[name] = gather_extra(name)
            except Exception:  # noqa: BLE001
                log(f"extra {name} failed:\n{traceback.format_exc()}")
    else:
        assign = [TRAIN_FOLDS[0::2], TRAIN_FOLDS[1::2]] if n_gpu >= 2 and len(TRAIN_FOLDS) > 1 else [TRAIN_FOLDS]
        plan = max(len(a) for a in assign)
        log(f"GPU fold assignment {assign} plan_folds={plan}")
        ctx = mp.get_context("fork")
        procs = []
        for g, folds in enumerate(assign):
            p = ctx.Process(target=gpu_worker, args=(g, folds, plan, len(assign)), daemon=False)
            p.start()
            procs.append(p)
            time.sleep(5)
        for name in ("static", "dynamic"):
            try:
                datasets[name] = gather_extra(name)
            except Exception:  # noqa: BLE001
                log(f"extra {name} failed:\n{traceback.format_exc()}")
        while any(p.is_alive() for p in procs):
            time.sleep(30)
        for g, p in enumerate(procs):
            p.join()
            log(f"gpu worker {g} exit code {p.exitcode}")
        DEV = torch.device("cuda")

    # ---- summaries
    fold_res = [json.loads((METRIC_DIR / f"fold{f}.json").read_text()) for f in TRAIN_FOLDS
                if (METRIC_DIR / f"fold{f}.json").exists()]
    summary = {"folds": fold_res}
    for key in ("ang_mae", "dice50"):
        vals = [r["tta_comp"][key] for r in fold_res if key in r.get("tta_comp", {})]
        if vals:
            summary[f"mean_tta_{key}"] = float(np.mean(vals))
    for key in ("vl_mid_med_err", "vl_deep_med_err", "vl_pa_field_mae", "vl_pa_field_bias", "vl_pa_head_mae",
                "vl_flrel_head_mae"):
        vals = [r["tta_vl"][key] for r in fold_res if key in r.get("tta_vl", {})]
        if vals:
            summary[f"mean_tta_{key}"] = float(np.nanmean(vals))
    bins = [r["tta_vl"]["vl_bin_median_err"] for r in fold_res if "vl_bin_median_err" in r.get("tta_vl", {})]
    if bins:
        summary["mean_tta_vl_bin_median_err"] = np.nanmean(np.asarray(bins, float), 0).round(3).tolist()
    (METRIC_DIR / "cv_summary.json").write_text(json.dumps(summary, indent=2, default=float))
    log("CV summary: " + json.dumps({k: v for k, v in summary.items() if k != "folds"}, default=float))

    # ---- fold models (ensemble for every image that no fold trained on)
    if DEV.type == "cpu":
        torch.set_num_threads(4)
    ckpts = sorted(CKPT_DIR.glob("fold*.pt"))
    if not ckpts:
        raise RuntimeError("no checkpoints were produced")
    models = []
    for cp in ckpts:
        m = build_model(pretrained=False)
        st = torch.load(cp, map_location="cpu", weights_only=False)
        m.load_state_dict({k: v.float() if v.is_floating_point() else v for k, v in st["state_dict"].items()})
        models.append(m.to(DEV).eval().to(memory_format=torch.channels_last))
    log(f"inference with {len(models)} fold models on {DEV}")
    manifest_rows: list[list] = []
    vp_rows: list[list] = []
    # VL files without an expert-line record (4 unparsed raw images + the annotated copies): never trained on ->
    # fold ensemble, written as one more part of the vl bank so it stays complete (as fasc_orient_v1's: 498 maps)
    used = {it["stem"] for it in VL_ITEMS}
    rest = [e for e in datasets.get("vl_all", []) if e[0] not in used]
    if CPU_SMOKE:
        rest = rest[:2]
    writers = {ch: NpzZip(OOF_PART_DIR / f"rest_vl_{ch}.npz", level=6) for ch in ALL_CHANNELS}
    for key, path, src in rest:
        try:
            gray = read_gray(path)
            box, kind = viewport(gray, path.suffix.lower())
            enc, _ = predict_native(models, gray, box, torch)
            for ch in ALL_CHANNELS:
                writers[ch].add(key, enc[ch])
            manifest_rows.append(["vl", key, src, gray.shape[0], gray.shape[1]])
            vp_rows.append(["vl", key, kind, *box])
        except Exception:  # noqa: BLE001
            log(f"inference failed vl/{src}:\n{traceback.format_exc()}")
    for w in writers.values():
        w.close()
    log(f"vl rest (no expert record; ensemble): {len(rest)} images")

    # ---- merge OOF parts (train_oof and VL out-of-fold maps)
    jobs = []
    for kind in ("train_oof", "vl"):
        for ch in ALL_CHANNELS:
            parts = [str(OOF_PART_DIR / f"fold{f}_{kind}_{ch}.npz") for f in TRAIN_FOLDS]
            if kind == "vl":
                parts.append(str(OOF_PART_DIR / f"rest_vl_{ch}.npz"))
            jobs.append((parts, str(MASKBANK / f"{kind}__{MODEL_NAME}_{ch}.npz")))
    for job in jobs:
        dest, n = _merge_job(job)
        log(f"merged {n} OOF maps -> {Path(dest).name}")
    for f in TRAIN_FOLDS:
        mp_path = OOF_PART_DIR / f"fold{f}_manifest.csv"
        if mp_path.exists():
            with open(mp_path) as fh:
                manifest_rows += list(csv.reader(fh))

    # ---- fold-ensemble + hflip TTA inference: test / static / dynamic (never trained on)
    run_inference(models, datasets, manifest_rows, vp_rows, torch)
    with open(MASKBANK / "manifest.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["dataset", "image_id", "source_filename", "height", "width"])
        w.writerows(manifest_rows)
    with open(MASKBANK / f"{MODEL_NAME}_viewports.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["dataset", "image_id", "layout", "x1", "y1", "x2", "y2"])
        w.writerows(vp_rows + [["vl", it["stem"], it["layout"], *it["box"]] for it in VL_ITEMS])
    config = {
        "model": MODEL_NAME, "mode": MODE, "encoder": ENCODER, "arch": "smp.Unet", "smp": smp.__version__,
        "torch": torch.__version__, "size": SIZE, "channels": {str(i): c for i, c in enumerate(ALL_CHANNELS)},
        "angle_convention": "theta = 0.5*atan2(sin2, cos2) in image pixel coords of the file (x right, y down)",
        "maskbank_encoding": "seg/cos2/sin2 as fasc_orient_v1; line = prob*255; pains = PA_deg/45*255; "
                             "flrel = log(FL/MT)/2.5*255",
        "vl": {"on": VL_ON, "repeat": VL_REPEAT, "ori_radius_px_at_512": VL_ORI_RADIUS, "deep_u": DEEP_U,
               "deep_boost": DEEP_BOOST, "ext_w": EXT_W, "w_vlori": W_VLORI, "w_line": W_LINE, "w_pa": W_PA,
               "w_flr": W_FLR, "source": "OSF xbawc Example Annotated Images (CC BY 4.0), parsed expert lines"},
        "train": {"batch": BATCH, "lr_enc": LR_ENC, "lr_dec": LR_DEC, "wd": WEIGHT_DECAY, "max_epochs": MAX_EPOCHS,
                  "folds": TRAIN_FOLDS, "seed": SEED, "budget_h": TRAIN_BUDGET_S / 3600},
        "data_stats": stats, "elapsed_min": (time.time() - T0) / 60, "note": NOTE,
    }
    (WORK / f"{MODEL_NAME}_config.json").write_text(json.dumps(config, indent=2, default=str))
    shutil.rmtree(TMP, ignore_errors=True)
    log(f"DONE elapsed={(time.time() - T0) / 60:.1f} min")


if __name__ == "__main__":
    main()
