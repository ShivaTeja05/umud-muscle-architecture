"""Build the v16 insfield Kaggle kernel folders (laptop, light; nothing is pushed).

    .venv/bin/python kaggle/v16_insfield/build_payload.py     # VL expert lines -> payload/ (once)
    .venv/bin/python kaggle/v16_insfield/build_driver.py      # train.py + kernel folders

1. assembles train.py = train_template.py + verbatim blocks of kaggle/fasc_orient_v1/train.py (the KG0 field recipe;
   its sha256 is checked, so a drift of the control code stops the build);
2. writes one folder per arm with run.py (train.py + payload embedded as zlib+base64, sha256-checked at run time) and
   kernel-metadata.json:
     cpusmoke/   shivateja005/umud-v16-insfield-cpusmoke   CPU, UMUD_MODE=cpusmoke (plumbing only, no GPU quota)
     A/          shivateja005/umud-v16-insfield-a          T4 x2, ConvNeXt-S 512, VL expert lines ON   (design A)
     A0/         shivateja005/umud-v16-insfield-a0         T4 x2, same code, VL OFF (control: v1 recipe re-run)
     C/          shivateja005/umud-v16-insfield-c          T4 x2, ConvNeXt-B fb_in22k 640, VL ON (only if A passes)
Push commands are in RUN.md. The GPU arms are for the judge to approve; this script never pushes.
"""
from __future__ import annotations

import base64
import hashlib
import json
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
V1 = ROOT / "kaggle/fasc_orient_v1/train.py"
V1_SHA = "e396d078794957eeb1a72c66469d13bf379688e6d918d83f8ba383886532abac"
BLOCKS = {  # 1-based inclusive line ranges of kaggle/fasc_orient_v1/train.py
    "A": (97, 339),    # logging, viewport (AmbrosM layout rules), fragment decomposition, read_gray, thumbnail, prep_train
    "B1": (340, 348),  # letterbox_matrix
    "B2": (368, 422),  # warp_image, _poly_mask, intensity_aug
    "C": (423, 461),   # render_targets (competition fragments)
    "D": (493, 558),   # make_input, unletterbox, encode_channels, NpzZip, merge_npz, _merge_job
    "E": (559, 578),   # ensure_smp
    "F": (944, 1109),  # find_dir, find_pairs, union_find_groups, assign_folds, prepare_items, download, gather_extra
}
ARMS = {
    "cpusmoke": {"id": "shivateja005/umud-v16-insfield-cpusmoke", "title": "UMUD v16 Insfield Cpusmoke", "gpu": False,
                 "env": {"UMUD_MODE": "cpusmoke", "UMUD_NOTE": "cpu smoke"}},
    "A": {"id": "shivateja005/umud-v16-insfield-a", "title": "UMUD v16 Insfield A", "gpu": True,
          "env": {"UMUD_MODE": "full", "UMUD_VL": "1", "UMUD_MODEL_NAME": "fasc_ins_v16", "UMUD_NOTE": "design A"}},
    "A0": {"id": "shivateja005/umud-v16-insfield-a0", "title": "UMUD v16 Insfield A0", "gpu": True,
           "env": {"UMUD_MODE": "full", "UMUD_VL": "0", "UMUD_MODEL_NAME": "fasc_ins_v16ctl",
                   "UMUD_NOTE": "control: VL off"}},
    "C": {"id": "shivateja005/umud-v16-insfield-c", "title": "UMUD v16 Insfield C", "gpu": True,
          "env": {"UMUD_MODE": "full", "UMUD_VL": "1", "UMUD_MODEL_NAME": "fasc_ins_v16c",
                  "UMUD_ENCODER": "tu-convnext_base.fb_in22k_ft_in1k", "UMUD_SIZE": "640", "UMUD_BATCH": "4",
                  "UMUD_TRAIN_BUDGET_H": "6.0", "UMUD_NOTE": "design C: ConvNeXt-B 640 + VL"}},
}

RUNNER = r'''"""UMUD v16 insfield runner (@@ARM@@). GENERATED by kaggle/v16_insfield/build_driver.py - do not edit.
Embedded (zlib+base64, sha256-checked): train.py, vl_lines.json (OSF xbawc Example Annotated Images, CC BY 4.0,
parsed expert lines), fasc_folds.csv (fasc_orient_v1 folds).
@@SHA_LINES@@
"""
import base64
import hashlib
import json
import os
import subprocess
import sys
import zlib
from pathlib import Path

ENV = @@ENV@@
SHA256 = @@SHA@@
BLOBS = @@BLOBS@@


def main():
    src = Path("/kaggle/working/insfield_src")
    src.mkdir(parents=True, exist_ok=True)
    for name, blob in BLOBS.items():
        data = zlib.decompress(base64.b64decode(blob))
        if hashlib.sha256(data).hexdigest() != SHA256[name]:
            raise RuntimeError(f"sha256 mismatch for {name}")
        (src / name).write_bytes(data)
    env = dict(os.environ, PYTHONUNBUFFERED="1", **ENV)
    print(f"[runner] env={json.dumps(ENV)} sha={json.dumps(SHA256)}", flush=True)
    rc = subprocess.call([sys.executable, "-u", str(src / "train.py")], env=env)
    print(f"[runner] train.py exit {rc}", flush=True)
    sys.exit(rc)


if __name__ == "__main__":
    main()
'''


def assemble() -> bytes:
    v1 = V1.read_bytes()
    if hashlib.sha256(v1).hexdigest() != V1_SHA:
        raise SystemExit(f"{V1} changed (sha256 != {V1_SHA}); re-check the block ranges")
    lines = v1.decode().splitlines(keepends=True)
    tpl = (HERE / "train_template.py").read_text()
    for name, (a, b) in BLOCKS.items():
        block = "".join(lines[a - 1:b])
        hdr = f"# ---- verbatim kaggle/fasc_orient_v1/train.py lines {a}-{b}\n"
        tag = f"@@BLOCK_{name}@@\n"
        if tpl.count(tag) != 1:
            raise SystemExit(f"template tag {tag!r} count != 1")
        tpl = tpl.replace(tag, hdr + block)
    tpl = tpl.replace("@@V1_SHA@@", V1_SHA)
    if "@@" in tpl:
        raise SystemExit("unreplaced template tag")
    return tpl.encode()


def main() -> None:
    train = assemble()
    (HERE / "train.py").write_bytes(train)
    payload = {"train.py": train,
               "vl_lines.json": (HERE / "payload/vl_lines.json").read_bytes(),
               "fasc_folds.csv": (HERE / "payload/fasc_folds.csv").read_bytes()}
    sha = {k: hashlib.sha256(v).hexdigest() for k, v in payload.items()}
    blobs = {k: base64.b64encode(zlib.compress(v, 9)).decode() for k, v in payload.items()}
    sha_lines = "\n".join(f"    {k}: {v}" for k, v in sha.items())
    for arm, cfg in ARMS.items():
        out = HERE / arm
        out.mkdir(parents=True, exist_ok=True)
        code = (RUNNER.replace("@@ARM@@", arm).replace("@@SHA_LINES@@", sha_lines)
                .replace("@@ENV@@", json.dumps(cfg["env"])).replace("@@SHA@@", json.dumps(sha, indent=4))
                .replace("@@BLOBS@@", json.dumps(blobs, indent=4)))
        (out / "run.py").write_text(code)
        meta = {"id": cfg["id"], "title": cfg["title"], "code_file": "run.py", "language": "python",
                "kernel_type": "script", "is_private": "true", "enable_gpu": "true" if cfg["gpu"] else "false",
                "enable_tpu": "false", "enable_internet": "true",
                "competition_sources": ["umud-challenge-muscle-architecture-in-ultrasound-data"],
                "dataset_sources": [], "kernel_sources": [], "model_sources": []}
        if cfg["gpu"]:
            meta["machine_shape"] = "NvidiaTeslaT4"
        (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
        print(f"{out / 'run.py'}: {len(code) / 1024:.0f} KiB env={cfg['env']}")
    for k, v in sha.items():
        print(f"  {k} {len(payload[k])} B sha256={v[:16]}")


if __name__ == "__main__":
    main()
