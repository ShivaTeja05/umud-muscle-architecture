def main() -> None:
    raw = {name: p.read_bytes() for name, p in SOURCES.items()}
    payload = {name: base64.b64encode(zlib.compress(b, 9)).decode("ascii") for name, b in raw.items()}
    shas = {name: hashlib.sha256(b).hexdigest() for name, b in raw.items()}
    (HERE / "sources_sha256.json").write_text(json.dumps(shas, indent=1) + "\n", encoding="utf-8")
    for folder, k in KERNELS.items():
        d = HERE if folder == "." else HERE / folder
        d.mkdir(exist_ok=True)
        (d / "kernel.py").write_text(LAUNCHER.format(smoke=k["smoke"], stages=repr(STAGES),
                                                     payload=json.dumps(payload, indent=0)), encoding="utf-8")
        meta = {"id": f"shivateja005/{k['slug']}", "title": k["title"], "code_file": "kernel.py", "language": "python",
                "kernel_type": "script", "is_private": "true", "enable_gpu": "false", "enable_tpu": "false",
                "enable_internet": "true", "competition_sources": [COMP], "dataset_sources": [],
                "kernel_sources": BASE_SOURCES, "model_sources": []}
        (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {d.relative_to(REPO)}/kernel.py ({(d / 'kernel.py').stat().st_size / 1e3:.0f} kB) "
              f"smoke={k['smoke']} stages={STAGES}")


if __name__ == "__main__":
    main()
