"""Build the LF-26 Kaggle kernel folders (laptop, light; nothing is pushed).

    cd <root> && lockf -k <SP>/laptop.lock env PYTHONPATH=src .venv/bin/python kaggle/longfasc_v26/build_driver.py
        [--payload-dir kaggle/longfasc_v26/payload] [--out-dir kaggle/longfasc_v26] [--allow-incomplete]

Writes one folder per arm with kernel.py (a runner that unpacks the embedded, zlib+base64, sha256-checked files into
/kaggle/working/lf26_src and runs train.py with UMUD_MODE) and kernel-metadata.json:
  gpu/       shivateja005/umud-longfasc-v26           T4 x2, internet on (FALLMUD CEA URL + OSF), UMUD_MODE=full
  cpusmoke/  shivateja005/umud-longfasc-v26-cpusmoke  CPU only, UMUD_MODE=cpusmoke (CPU-safe dry run)
Embedded: train.py (= train_template.py), geometry_v2.py (src/umud/geometry_v2.py), lf_readout.py
(artifacts/candidates_v26/code/lf_readout.py), payload/*.json.gz + payload_summary.json (export_payload.py) and, if
the laptop L0 runs exist (artifacts/candidates_v26/runs/L0_prod_<set>.csv), payload/l0_ref.json for the in-kernel
port check. Both kernels attach shivateja005/umud-fasc-orient-v1 (v1 folds.csv, fold checkpoints, maskbank).
The gpu/ folder is written only from a complete payload (761 images + VL expert), unless --allow-incomplete (then
build_info.json says so and the kernel itself refuses MODE=full). build_info.json records every sha256 and size.
r1 (PREREG_v26_r1.json): l0_ref carries [fl_vwmed, fl_fixed] of the laptop L0 runs for the production geometry
(4 sets) and the VL expert geometry ({"prod": ..., "expert": ...}); the sha256 of the hashed pre-registration files
are embedded in kernel.py (docstring + PREREG dict, written by the runner to lf26_prereg_config.json) so that the
Kaggle version timestamp witnesses them; --slim-frags (default on) zeroes the information-only fragment fields
vx, vy, length of the embedded geometry payloads (the readout reads cx, cy only; local_port_check.py verifies the
readout is unchanged) to keep kernel.py under ~1 MB.
GPL-3.0-only.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import zlib
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
V3_SRC = REPO / "kaggle/fasc_orient_v3/train.py"
V3_SHA = "a7778983bcedbb1d8b92b03570837276e29c8b1463a91731ab2c44db76e64706"
SIZE_WARN = 1_000_000  # bytes of kernel.py
COMP = "umud-challenge-muscle-architecture-in-ultrasound-data"
ARMS = {
    "gpu": {"id": "shivateja005/umud-longfasc-v26", "title": "UMUD LongFasc v26", "gpu": True,
            "env": {"UMUD_MODE": "full"}},
    "cpusmoke": {"id": "shivateja005/umud-longfasc-v26-cpusmoke", "title": "UMUD LongFasc v26 Cpusmoke", "gpu": False,
                 "env": {"UMUD_MODE": "cpusmoke"}},
}

RUNNER = r'''"""UMUD LF-26 runner (@@ARM@@). GENERATED by kaggle/longfasc_v26/build_driver.py - do not edit.
Embedded (zlib+base64, sha256-checked at run time): train.py (LFNet-v26 trainer + in-kernel LF readout),
geometry_v2.py and lf_readout.py (the laptop's readout code), payload/ (production geometry of the evaluation images
exported on the laptop: no FL / PA / MT labels). Pre-registration (sha256, hashed on the laptop before this build):
@@PREREG_LINES@@
GPL-3.0-only.
Embedded files (sha256):
@@SHA_LINES@@
"""
import base64
import hashlib
import json
import os
import subprocess
import sys
import zlib
from pathlib import Path

ENV = @@ENV@@
PREREG = @@PREREG@@
SHA256 = @@SHA@@
BLOBS = @@BLOBS@@


def main():
    src = Path("/kaggle/working/lf26_src")
    for name, blob in BLOBS.items():
        data = zlib.decompress(base64.b64decode(blob))
        if hashlib.sha256(data).hexdigest() != SHA256[name]:
            raise RuntimeError(f"sha256 mismatch for {name}")
        p = src / name
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
    Path("/kaggle/working").mkdir(parents=True, exist_ok=True)
    Path("/kaggle/working/lf26_prereg_config.json").write_text(json.dumps(dict(prereg_sha256=PREREG, files_sha256=SHA256,
                                                                                env=ENV), indent=1))
    env = dict(os.environ, PYTHONUNBUFFERED="1", UMUD_SRC=str(src), **ENV)
    print(f"[runner] env={json.dumps(ENV)} prereg={json.dumps(PREREG)} files={len(BLOBS)} sha={json.dumps(SHA256)}",
          flush=True)
    rc = subprocess.call([sys.executable, "-u", str(src / "train.py")], env=env, cwd=str(src))
    print(f"[runner] train.py exit {rc}", flush=True)
    sys.exit(rc)


if __name__ == "__main__":
    main()
'''


def sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


PREREG_FILES = ("PREREG_v26_longfasc.json", "PREREG_v26_r1.json", "PREREG_v26_addendum_K.json",
                "PREREG_v26_addendum_K_r1.json")


def _val(v):
    return None if pd.isna(v) else float(v)


def l0_ref(tag: str = "") -> dict:
    """r1: {"prod": {"set|image_id": [fl_vwmed, fl_fixed]}, "expert": {"vl|image_id": [...]}} from the laptop L0 runs
    (only images whose readout status is ok; the kernel compares its port runs at the r1 tolerance)."""
    out = {"prod": {}, "expert": {}}
    runs = [("prod", s, f"L0_prod_{s}") for s in ("test", "static", "dynamic", "vl")] + [("expert", "vl", "L0_expert_vl")]
    for part, s, stem in runs:
        p = REPO / f"artifacts/candidates_v26/runs/{stem}{'_' + tag if tag else ''}.csv"
        if p.exists():
            d = pd.read_csv(p).drop_duplicates("image_id", keep="last")
            for r in d.itertuples():
                if getattr(r, "status", "ok") != "ok":
                    continue
                out[part][f"{s}|{r.image_id}"] = [_val(getattr(r, "fl_vwmed", float("nan"))),
                                                  _val(getattr(r, "fl_fixed", float("nan")))]
    return {k: v for k, v in out.items() if v}


def slim_geom_gz(raw: bytes) -> bytes:
    """Zero the information-only fragment fields (vx, vy, length) of a geom_*.json.gz payload; cx, cy and every other
    value unchanged (same JSON separators, gzip mtime 0, level 9 as export_payload.write_gz)."""
    import gzip
    import io
    recs = json.loads(gzip.decompress(raw))
    for r in recs:
        g = r.get("geom")
        if g and g.get("frags"):
            g["frags"] = [[f[0], f[1], 0, 0, 0] for f in g["frags"]]
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", mtime=0, compresslevel=9) as gz:
        gz.write(json.dumps(recs, separators=(",", ":")).encode())
    return buf.getvalue()


def prereg_shas() -> dict:
    out = {}
    for n in PREREG_FILES:
        p = REPO / "artifacts/candidates_v26" / n
        out[n] = sha(p.read_bytes()) if p.exists() else None
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--payload-dir", default=str(HERE / "payload"))
    ap.add_argument("--out-dir", default=str(HERE))
    ap.add_argument("--allow-incomplete", action="store_true")
    ap.add_argument("--l0-tag", default="", help="read runs/L0_prod_<set>_<tag>.csv (smoke builds)")
    ap.add_argument("--no-slim-frags", action="store_true", help="embed the payload files unchanged")
    a = ap.parse_args(argv)
    pre = prereg_shas()
    if not all(pre.values()):
        raise SystemExit(f"hashed pre-registration files missing: {[k for k, v in pre.items() if not v]}")
    for n in PREREG_FILES:  # each file must match its .sha256 record
        rec = (REPO / "artifacts/candidates_v26" / n.replace(".json", ".sha256")).read_text().split()[0]
        if rec != pre[n]:
            raise SystemExit(f"{n}: sha256 {pre[n][:12]} != its .sha256 record {rec[:12]}")
    tmpl_sha = sha((HERE / "train_template.py").read_bytes())
    k_r1 = json.loads((REPO / "artifacts/candidates_v26/PREREG_v26_addendum_K_r1.json").read_text())
    if k_r1.get("template_sha256") != tmpl_sha:
        raise SystemExit(f"train_template.py sha256 {tmpl_sha[:12]} != addendum K_r1 template_sha256")
    pay, out_root = Path(a.payload_dir), Path(a.out_dir)
    v3 = V3_SRC.read_bytes()
    if sha(v3) != V3_SHA:
        raise SystemExit(f"{V3_SRC} changed since the template was copied (sha256 != {V3_SHA[:12]})")
    summ_p = pay / "payload_summary.json"
    summ = json.loads(summ_p.read_text()) if summ_p.exists() else {}
    complete = bool(summ.get("complete"))
    if not complete and not a.allow_incomplete:
        raise SystemExit(f"payload in {pay} is incomplete (run export_payload.py for test/static/dynamic/vl + "
                         f"--summary); use --allow-incomplete only for smoke builds outside kaggle/longfasc_v26")
    files = {"train.py": (HERE / "train_template.py").read_bytes(),
             "geometry_v2.py": (REPO / "src/umud/geometry_v2.py").read_bytes(),
             "lf_readout.py": (REPO / "artifacts/candidates_v26/code/lf_readout.py").read_bytes()}
    orig_sha = {}
    for p in sorted(pay.glob("*.json.gz")):
        raw = p.read_bytes()
        orig_sha[f"payload/{p.name}"] = sha(raw)
        files[f"payload/{p.name}"] = slim_geom_gz(raw) if (p.name.startswith("geom_") and not a.no_slim_frags) else raw
    if summ_p.exists():
        files["payload/payload_summary.json"] = summ_p.read_bytes()
    ref = l0_ref(a.l0_tag)
    if ref:
        files["payload/l0_ref.json"] = json.dumps(ref, sort_keys=True).encode()
    shas = {k: sha(v) for k, v in files.items()}
    blobs = {k: base64.b64encode(zlib.compress(v, 9)).decode() for k, v in files.items()}
    sha_lines = "\n".join(f"    {k}: {v}" for k, v in shas.items())
    prereg_lines = "\n".join(f"    {k}: {v}" for k, v in pre.items())
    info = dict(built_utc=datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), payload_dir=str(pay),
                payload_complete=complete, payload_summary_sha256=sha(summ_p.read_bytes()) if summ_p.exists() else None,
                template_from=dict(file=str(V3_SRC.relative_to(REPO)), sha256=V3_SHA), prereg_sha256=pre,
                slim_frags=not a.no_slim_frags, payload_file_sha256_before_slim=orig_sha,
                files={k: dict(bytes=len(v), sha256=shas[k]) for k, v in files.items()},
                l0_ref_images={k: len(v) for k, v in ref.items()}, arms={})
    for arm, cfg in ARMS.items():
        out = out_root / arm
        out.mkdir(parents=True, exist_ok=True)
        code = (RUNNER.replace("@@ARM@@", arm).replace("@@SHA_LINES@@", sha_lines)
                .replace("@@PREREG_LINES@@", prereg_lines).replace("@@PREREG@@", json.dumps(pre, indent=4))
                .replace("@@ENV@@", json.dumps(cfg["env"])).replace("@@SHA@@", json.dumps(shas, indent=4))
                .replace("@@BLOBS@@", json.dumps(blobs, indent=4)))
        (out / "kernel.py").write_text(code)
        meta = {"id": cfg["id"], "title": cfg["title"], "code_file": "kernel.py", "language": "python",
                "kernel_type": "script", "is_private": "true", "enable_gpu": "true" if cfg["gpu"] else "false",
                "enable_tpu": "false", "enable_internet": "true", "competition_sources": [COMP],
                "dataset_sources": [], "kernel_sources": ["shivateja005/umud-fasc-orient-v1"], "model_sources": []}
        if cfg["gpu"]:
            meta["machine_shape"] = "NvidiaTeslaT4"
        (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
        n = len(code.encode())
        info["arms"][arm] = dict(id=cfg["id"], env=cfg["env"], kernel_py_bytes=n, kernel_py_sha256=sha(code.encode()),
                                 size_warning=n > SIZE_WARN)
        print(f"{out / 'kernel.py'}: {n / 1024:.0f} KiB env={cfg['env']}{'  WARNING > 1 MB' if n > SIZE_WARN else ''}")
    (out_root / "build_info.json").write_text(json.dumps(info, indent=1))
    for k, v in info["files"].items():
        print(f"  {k} {v['bytes']} B sha256={v['sha256'][:16]}")
    print(f"payload complete={complete} l0_ref={ {k: len(v) for k, v in ref.items()} } images prereg={ {k: v[:12] for k, v in pre.items()} }")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
