"""Generate kernel.py + kernel-metadata.json for shivateja005/umud-auto-expert-maps (never pushes).

AUTO-EXPERT (artifacts/candidates_v23/auto_expert/PREREG_auto_expert.json): the production (KG0) map models on the 96
WRK work frames, CPU only. kernel.py embeds (zlib + base64), unchanged:
  apo_fix_src.py = kaggle/apo_v2_fix/ext/infer_fix_ext.py   (apo_v2fix model, BN fix, letterbox, NpzWriter)
  fo_src.py      = kaggle/fasc_orient_v1/train.py           (fasc_orient_v1 model, viewport, TTA forward, NpzZip)
  wrk_stages.py  = kaggle/auto_expert_maps/wrk_stages.py    (data stage for the WRK zip + the TT-BENCH map stages)
plus the per-frame table of the 96 main WRK frames read from the LOCAL work manifest (size, corrected viewport and
px_per_cm, participant, PNG sha256), as kaggle/labelling_suggest/build_kernel.py does. Nothing from
data/manual_labelling/private/ is embedded or read.

  .venv/bin/python kaggle/auto_expert_maps/build_kernel.py [--smoke N]
Push (after review):  .venv/bin/kaggle kernels push -p kaggle/auto_expert_maps
Fetch only the maps the measurement needs + manifest + logs (see the PREREG):
  .venv/bin/kaggle kernels output shivateja005/umud-auto-expert-maps -p <dir> --force --file-pattern
     '.*(manifest\\.csv|data_info\\.json|exit_codes\\.json|\\.log|fix_report_wrk\\.json|run_info_ours_wrk\\.json|viewports_wrk\\.csv|wrk__(apo_v2fix_(band|upper|lower)|ours_apo384_noflip|ours_fasc384_noflip|fasc_orient_v1_(seg|cos2|sin2))\\.npz)$'
GPL-3.0-only.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
SOURCES = {"apo_fix_src.py": REPO / "kaggle/apo_v2_fix/ext/infer_fix_ext.py",
           "fo_src.py": REPO / "kaggle/fasc_orient_v1/train.py",
           "wrk_stages.py": HERE / "wrk_stages.py"}
WORK_MANIFEST = REPO / "data/manual_labelling/work/manifest.json"
COMP = "umud-challenge-muscle-architecture-in-ultrasound-data"
KERNEL_SOURCES = ["shivateja005/umud-apo-v2", "shivateja005/umud-fasc-orient-v1",
                  "shivateja005/umud-u-net-aponeurosis-384-cli", "shivateja005/umud-u-net-fascicle-384-cli",
                  "shivateja005/umud-labelling-frames"]
STAGES = ["data", "apo", "ours", "orient"]

LAUNCHER = '''"""UMUD AUTO-EXPERT maps launcher (generated by kaggle/auto_expert_maps/build_kernel.py). GPL-3.0-only.

Stages data -> apo -> ours -> orient of wrk_stages.py, each in its own subprocess (CPU). Outputs /kaggle/working/wrk_out.
"""
import base64, json, os, subprocess, sys, time, zlib
from pathlib import Path

SMOKE = {smoke}
STAGES = {stages}
SOURCE_SHA256 = {source_sha}
TABLE = {table}
SOURCES = {payload}
TMP = Path("/tmp/wrk")
OUT = Path("/kaggle/working/wrk_out")
T0 = time.time()


def say(msg):
    print(f"[launcher {{time.time() - T0:7.1f}}s] {{msg}}", flush=True)


def run(stage):
    env = dict(os.environ, TT_SMOKE=str(SMOKE), PYTHONUNBUFFERED="1")
    (OUT / "logs").mkdir(parents=True, exist_ok=True)
    t = time.time()
    with (OUT / "logs" / f"{{stage}}.log").open("w", encoding="utf-8") as lf:
        p = subprocess.Popen([sys.executable, "-u", str(TMP / "wrk_stages.py"), "--stage", stage], cwd=str(TMP),
                             stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, env=env)
        for line in p.stdout:
            print(f"[{{stage}}] {{line}}", end="", flush=True)
            lf.write(line)
        code = p.wait()
    say(f"stage {{stage}} exit={{code}} {{time.time() - t:.0f}}s")
    return code


def main():
    TMP.mkdir(parents=True, exist_ok=True)
    OUT.mkdir(parents=True, exist_ok=True)
    for name, blob in SOURCES.items():
        (TMP / name).write_text(zlib.decompress(base64.b64decode(blob)).decode("utf-8"), encoding="utf-8")
    (TMP / "frames_table.json").write_text(json.dumps(TABLE), encoding="utf-8")
    say(f"python={{sys.version.split()[0]}} cpus={{os.cpu_count()}} smoke={{SMOKE}} stages={{STAGES}} "
        f"frames in table={{len(TABLE)}}")
    codes = {{}}
    for st in STAGES:
        codes[st] = run(st)
        if st == "data" and codes[st] != 0:
            break
    (OUT / "exit_codes.json").write_text(json.dumps({{"exit_codes": codes, "source_sha256": SOURCE_SHA256,
                                                      "smoke": SMOKE, "minutes": (time.time() - T0) / 60}}))
    say(f"exit codes {{codes}}")
    for p in sorted(OUT.rglob("*")):
        if p.is_file():
            say(f"  {{p.relative_to(OUT)}} {{p.stat().st_size / 1e6:.3f}} MB")


main()
'''


def sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def frames_table() -> dict:
    """Per main frame of the local work manifest: size, viewport, px_per_cm, participant, PNG sha256."""
    man = json.loads(WORK_MANIFEST.read_text(encoding="utf-8"))
    out = {}
    for e in man["images"]:
        if e.get("view_only"):
            continue
        png = WORK_MANIFEST.parent / e["file"]
        out[e["image_id"]] = {"width": int(e["width"]), "height": int(e["height"]),
                              "viewport": [int(v) for v in e["viewport"]], "px_per_cm": float(e["px_per_cm"]),
                              "participant": e.get("participant"), "sha256": sha256_bytes(png.read_bytes())}
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", type=int, default=0, help="only the first N frames (0 = all)")
    args = ap.parse_args()
    texts = {name: p.read_text(encoding="utf-8") for name, p in SOURCES.items()}
    payload = {name: base64.b64encode(zlib.compress(t.encode("utf-8"), 9)).decode("ascii") for name, t in texts.items()}
    source_sha = {name: sha256_bytes(t.encode("utf-8")) for name, t in texts.items()}
    table = frames_table()
    if len(table) != 96:
        raise SystemExit(f"expected 96 main frames, got {len(table)}")
    print(f"table: {len(table)} frames, participants {sorted({v['participant'] for v in table.values()})}, "
          f"px_per_cm {sorted({v['px_per_cm'] for v in table.values()})}, "
          f"viewports {sorted({tuple(v['viewport']) for v in table.values()})}")
    code = LAUNCHER.format(smoke=int(args.smoke), stages=repr(STAGES), source_sha=repr(source_sha),
                           table=repr(dict(sorted(table.items()))), payload=json.dumps(payload, indent=0))
    compile(code, "kernel.py", "exec")
    (HERE / "kernel.py").write_text(code, encoding="utf-8")
    meta = {"id": "shivateja005/umud-auto-expert-maps", "title": "UMUD Auto Expert Maps", "code_file": "kernel.py",
            "language": "python", "kernel_type": "script", "is_private": "true", "enable_gpu": "false",
            "enable_tpu": "false", "enable_internet": "true", "competition_sources": [COMP], "dataset_sources": [],
            "kernel_sources": KERNEL_SOURCES, "model_sources": []}
    (HERE / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    print(f"wrote kernel.py ({(HERE / 'kernel.py').stat().st_size / 1e3:.0f} kB), kernel-metadata.json; "
          f"sources {source_sha}")


if __name__ == "__main__":
    main()
