def load_helpers():
    spec = importlib.util.spec_from_file_location("adabn_stages_local", HERE / "adabn_stages.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules["adabn_stages_local"] = mod
    spec.loader.exec_module(mod)  # top level imports numpy / stdlib only
    return mod


def sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def read_csv(path: Path) -> list[dict]:
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def build_tables(h) -> dict:
    lay = read_csv(REPO / "artifacts/final/test_layout.csv")
    test_group = {Path(r["image_id"]).stem: GROUP_CODE[r["group"]] for r in lay}
    if len(test_group) != 309:
        raise SystemExit(f"test layout: {len(test_group)} rows")
    vl = sorted(read_csv(REPO / "artifacts/maskbank/vl_data/vl_index.csv"), key=lambda r: r["key"])
    if len(vl) != 249:
        raise SystemExit(f"vl_index: {len(vl)} rows")
    vl_tails = [h.tail3(r["raw_source"]) for r in vl]
    if len(set(vl_tails)) != 249:
        raise SystemExit("VL raw tails are not unique")
    # per-network VL key of the first 2 VL frames
    apo_vl = {h.tail3(r["source_filename"]): r["image_id"]
              for r in read_csv(BANKS["apo"][0] / "manifest_ext.csv") if r["dataset"] == "vl"}
    ori_vl = {h.tail3(r["source_filename"]): r["image_id"]
              for r in read_csv(BANKS["orient"][0] / "manifest.csv")
              if r["dataset"] == "vl" and r["source_filename"].lower().endswith(".tiff")}
    if not (set(vl_tails) <= set(apo_vl) and set(vl_tails) <= set(ori_vl)):
        raise SystemExit("VL raw frames missing from the apo / orient manifests")
    by_group: dict = {}
    for stem in sorted(test_group):
        by_group.setdefault(test_group[stem], []).append(stem)
    subset = [("test", s) for g in ("SIE", "LUM", "T12", "T10", "LEG") for s in by_group[g][:2]]
    subset += [("static", s) for s in REPRO_STATIC] + [("dynamic", s) for s in REPRO_DYNAMIC]
    vl_pick = vl[:2]
    repro = {}
    for net, (bank, models) in BANKS.items():
        entries = []
        keys = list(subset)
        for r in vl_pick:
            t = h.tail3(r["raw_source"])
            keys.append(("vl", {"apo": apo_vl[t], "orient": ori_vl[t], "ours": r["key"]}[net]))
        for ds, key in keys:
            maps = {}
            for mn in models:
                with np.load(bank / f"{ds}__{mn}.npz") as f:
                    a = f[key]
                maps[mn] = {"shape": list(a.shape), "sha1": h.arr_sha1(a),
                            "bm": np.round(h.block_means(a), 3).tolist()}
            entries.append({"ds": ds, "key": key, "maps": maps})
        repro[net] = entries
    fix = json.loads(FIX_REPORT.read_text())
    apo_fix_expected = {k: {m: v["check"][v["chosen"]][m] for m in ("dice", "score", "mt_rel_edge")}
                        for k, v in fix.items()}
    frozen = {}
    for net, (bank, models) in BANKS.items():
        for ds in ("test", "static", "dynamic", "vl"):
            for mn in models:
                p = bank / f"{ds}__{mn}.npz"
                frozen[f"{net}/{p.name}"] = sha256_file(p)
    return {"test_group": test_group, "vl_raw_tails": vl_tails, "vl_index_keys": [r["key"] for r in vl],
            "repro": repro, "apo_fix_expected": apo_fix_expected, "orient_bad_expected": {"2": 45, "4": 29},
            "ckpt_sha256": {OURS_CKPT.name: sha256_file(OURS_CKPT)}, "frozen_bank_sha256": frozen}


def sha256_file(path: Path) -> str:
    hh = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            hh.update(chunk)
    return hh.hexdigest()


def write_kernel(dest: Path, mode: str, payload: dict, source_sha: dict, tables: dict) -> None:
    tz = base64.b64encode(zlib.compress(json.dumps(tables, sort_keys=True).encode("utf-8"), 9)).decode("ascii")
    code = (LAUNCHER.replace("@@MODE@@", mode).replace("@@SOURCE_SHA@@", repr(source_sha))
            .replace("@@PAYLOAD@@", json.dumps(payload, indent=0)).replace("@@TABLES@@", tz))
    compile(code, "kernel.py", "exec")
    dest.mkdir(parents=True, exist_ok=True)
    (dest / "kernel.py").write_text(code, encoding="utf-8")
    full = mode == "full"
    meta = {"id": "shivateja005/umud-adabn-v25" + ("" if full else "-cpusmoke"),
            "title": "UMUD AdaBN v25" + ("" if full else " cpusmoke"), "code_file": "kernel.py",
            "language": "python", "kernel_type": "script", "is_private": "true",
            "enable_gpu": "true" if full else "false", "enable_tpu": "false", "enable_internet": "true",
            "competition_sources": [COMP], "dataset_sources": [], "kernel_sources": KERNEL_SOURCES,
            "model_sources": []}
    if full:
        meta["machine_shape"] = "NvidiaTeslaT4"
    (dest / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {dest / 'kernel.py'} ({(dest / 'kernel.py').stat().st_size / 1e3:.0f} kB) + kernel-metadata.json "
          f"[{meta['id']}]")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.parse_args()
    if not PREREG.exists():
        raise SystemExit(f"{PREREG} must be written before the kernel is built")
    if not ADDENDUM.exists():
        raise SystemExit(f"{ADDENDUM} must be written before the kernel is built")
    json.loads(ADDENDUM.read_text(encoding="utf-8"))  # must be valid JSON
    h = load_helpers()
    texts = {name: p.read_text(encoding="utf-8") for name, p in SOURCES.items()}
    payload = {n: base64.b64encode(zlib.compress(t.encode("utf-8"), 9)).decode("ascii") for n, t in texts.items()}
    source_sha = {n: sha256_bytes(t.encode("utf-8")) for n, t in texts.items()}
    tables = build_tables(h)
    tables.update(prereg_sha256=sha256_file(PREREG), addendum_sha256=sha256_file(ADDENDUM), source_sha256=source_sha,
                  built=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()))
    print(f"tables: test {len(tables['test_group'])}, VL {len(tables['vl_raw_tails'])}, repro "
          f"{ {n: len(v) for n, v in tables['repro'].items()} }, prereg {tables['prereg_sha256'][:16]}")
    write_kernel(HERE, "full", payload, source_sha, tables)
    write_kernel(HERE / "cpusmoke", "cpusmoke", payload, source_sha, tables)
    (HERE / "build_info.json").write_text(json.dumps({"source_sha256": source_sha, "prereg_sha256":
                                                      tables["prereg_sha256"],
                                                      "addendum_sha256": tables["addendum_sha256"],
                                                      "built": tables["built"],
                                                      "ckpt_sha256": tables["ckpt_sha256"],
                                                      "kernel_sources": KERNEL_SOURCES}, indent=1) + "\n")


if __name__ == "__main__":
    main()
