"""Write kaggle/s5_direct_v30/{gpu,cpusmoke}/run.py + kernel-metadata.json and build_info.json.

    lockf -k <scratchpad>/laptop.lock env PYTHONPATH=src .venv/bin/python kaggle/s5_direct_v30/build_driver.py

run.py embeds s5_train.py and every payload file (zlib + base64), checks their sha256 at run time, writes them to
/tmp/s5_src (never to /kaggle/working) and runs s5_train.py with UMUD_S5_MODE = gpu | cpusmoke. Both folders embed
byte-identical code; only the mode and the kernel metadata differ. Refuses to build if the payload summary does not
match the payload files. Push commands: RUN.md (this script never pushes).
"""
from __future__ import annotations

import base64
import hashlib
import json
import time
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAYLOAD = ("vl_lines.json", "tt_labels.csv", "dyn_labels.csv", "geom.csv", "ids.json")
ARMS = {
    "gpu": {"id": "shivateja005/umud-s5-direct-v30", "title": "UMUD S5 Direct v30", "gpu": True,
            "env": {"UMUD_S5_MODE": "gpu"}},
    "cpusmoke": {"id": "shivateja005/umud-s5-direct-v30-cpusmoke", "title": "UMUD S5 Direct v30 Cpusmoke",
                 "gpu": False, "env": {"UMUD_S5_MODE": "cpusmoke"}},
}
RUNNER = r'''# UMUD Challenge solution code -- v30 S5 direct regressor runner (@@ARM@@)
# Copyright (C) 2026 Gaddam Shivateja
# SPDX-License-Identifier: GPL-3.0-only
# This program is free software: you can redistribute it and/or modify it under the terms of the GNU General Public
# License as published by the Free Software Foundation, version 3 (GPL-3.0-only). It is distributed in the hope that
# it will be useful, but WITHOUT ANY WARRANTY; see <https://www.gnu.org/licenses/gpl-3.0.txt>.
"""GENERATED by kaggle/s5_direct_v30/build_driver.py - do not edit. Pre-registration:
artifacts/candidates_v30/s5/PREREG_v30_s5.json. Embedded (zlib+base64, sha256-checked at run time):
@@SHA_LINES@@
"""
import base64
import hashlib
import json
import os
import subprocess
import sys
import zlib
from pathlib import Path

ENV = @@ENV@@
SHA256 = @@SHA@@
BLOBS = @@BLOBS@@


def main():
    src = Path("/tmp/s5_src")
    src.mkdir(parents=True, exist_ok=True)
    for name, blob in BLOBS.items():
        data = zlib.decompress(base64.b64decode(blob))
        if hashlib.sha256(data).hexdigest() != SHA256[name]:
            raise RuntimeError(f"sha256 mismatch for {name}")
        (src / name).write_bytes(data)
    env = dict(os.environ, PYTHONUNBUFFERED="1", UMUD_S5_SRC=str(src), **ENV)
    print(f"[runner] env={json.dumps(ENV)} sha={json.dumps(SHA256)}", flush=True)
    rc = subprocess.call([sys.executable, "-u", str(src / "s5_train.py")], env=env, cwd="/kaggle/working")
    print(f"[runner] s5_train.py exit {rc}", flush=True)
    sys.exit(rc)


if __name__ == "__main__":
    main()
'''


def main() -> None:
    summ = json.loads((HERE / "payload/payload_summary.json").read_text())
    payload = {"s5_train.py": (HERE / "s5_train.py").read_bytes()}
    for name in PAYLOAD:
        b = (HERE / "payload" / name).read_bytes()
        if hashlib.sha256(b).hexdigest() != summ["files"][name]["sha256"]:
            raise SystemExit(f"payload/{name} does not match payload_summary.json; rebuild the payload")
        payload[name] = b
    sha = {k: hashlib.sha256(v).hexdigest() for k, v in payload.items()}
    blobs = {k: base64.b64encode(zlib.compress(v, 9)).decode() for k, v in payload.items()}
    sha_lines = "\n".join(f"    {k}: {v}" for k, v in sha.items())
    info = {"built_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "embedded_sha256": sha,
            "embedded_bytes": {k: len(v) for k, v in payload.items()}, "arms": {}}
    for arm, cfg in ARMS.items():
        out = HERE / arm
        out.mkdir(parents=True, exist_ok=True)
        code = (RUNNER.replace("@@ARM@@", arm).replace("@@SHA_LINES@@", sha_lines)
                .replace("@@ENV@@", json.dumps(cfg["env"])).replace("@@SHA@@", json.dumps(sha, indent=4))
                .replace("@@BLOBS@@", json.dumps(blobs, indent=4)))
        (out / "run.py").write_text(code)
        meta = {"id": cfg["id"], "title": cfg["title"], "code_file": "run.py", "language": "python",
                "kernel_type": "script", "is_private": "true", "enable_gpu": "true" if cfg["gpu"] else "false",
                "enable_tpu": "false", "enable_internet": "true",
                "competition_sources": ["umud-challenge-muscle-architecture-in-ultrasound-data"],
                "dataset_sources": [], "kernel_sources": [], "model_sources": []}
        if cfg["gpu"]:
            meta["machine_shape"] = "NvidiaTeslaT4"
        (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
        info["arms"][arm] = {"id": cfg["id"], "env": cfg["env"], "gpu": cfg["gpu"],
                             "run.py_sha256": hashlib.sha256(code.encode()).hexdigest(), "run.py_bytes": len(code.encode())}
        print(f"{out / 'run.py'}: {len(code) / 1024:.0f} KiB env={cfg['env']}")
    (HERE / "build_info.json").write_text(json.dumps(info, indent=1) + "\n")
    for k, v in sha.items():
        print(f"  {k} {len(payload[k])} B sha256={v[:16]}")


if __name__ == "__main__":
    main()
