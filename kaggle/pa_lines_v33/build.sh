#!/bin/sh
# Builds the single-file Kaggle trainer: fasc_orient_v1 base + v33 overlay. Usage: sh build.sh
set -e
cd "$(dirname "$0")"
BASE=../fasc_orient_v1/train.py
FOLDS=${FOLDS:-[0]}  # full-mode folds; staged run trains fold 0 only. All folds: FOLDS="[0, 1, 2, 3, 4]" sh build.sh
BUILD_ROOT=${PA_V33_BUILD_ROOT:-.}
N=$(grep -n '^if __name__ == "__main__":' "$BASE" | cut -d: -f1)
for MODE in cpusmoke full; do
  DIR="$BUILD_ROOT/$([ "$MODE" = cpusmoke ] && echo cpusmoke || echo gpu)"
  mkdir -p "$DIR"
  {
    echo '# SPDX-License-Identifier: GPL-3.0-or-later'
    echo '# UMUD pa_lines_v33: fascicle direction + deep aponeurosis edge + read-weight map, trained on the'
    echo '# measured angle through a parameter-free readout. GENERATED by kaggle/pa_lines_v33/build.sh from'
    echo '# kaggle/fasc_orient_v1/train.py (base) and kaggle/pa_lines_v33/src/part_*.py (overlay). Do not edit.'
    head -n $((N - 1)) "$BASE" | sed -e "s/^MODE = \"full\".*/MODE = \"$MODE\"  # cpusmoke | smoke | full/" \
      -e 's/^SMOKE = MODE == "smoke"/SMOKE = MODE != "full"/' \
      -e "s/^TRAIN_FOLDS = \[0, 1\] if SMOKE else .*/TRAIN_FOLDS = [0] if SMOKE else $FOLDS/"
    cat src/part_pairs.py src/part_a.py src/part_b.py src/part_c.py
  } > "$DIR/train.py"
done
