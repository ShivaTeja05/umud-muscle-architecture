def extract_members(archive: Path, members: list[str], dest: Path) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    root = dest.resolve()
    with zipfile.ZipFile(archive) as zf:
        names = set(zf.namelist())
        for name in members:
            if name not in names:
                raise FileNotFoundError(f"{name} not in {archive}")
            target = (dest / name).resolve()
            if not str(target).startswith(str(root) + os.sep):
                raise ValueError(f"unsafe member {name!r}")
            target.parent.mkdir(parents=True, exist_ok=True)
            with zf.open(name) as src, target.open("wb") as dst:
                shutil.copyfileobj(src, dst)


def stage_data() -> None:
    log(f"input tree of {INPUT}:")
    print_input_tree(INPUT)
    kind, src = find_work_source()
    log(f"work source: {kind} {src}")
    if kind == "zip":
        with zipfile.ZipFile(src) as zf:
            names = zf.namelist()
        man_names = [n for n in names if n.endswith("manifest.json") and "/img/" not in n and "private" not in n]
        if not man_names:
            raise FileNotFoundError(f"no manifest.json in {src}")
        man_name = sorted(man_names, key=len)[0]
        prefix = man_name[: -len("manifest.json")]
        extract_members(src, [man_name], TMP / "zip")
        manifest = json.loads((TMP / "zip" / man_name).read_text(encoding="utf-8"))
        main = [e for e in manifest["images"] if not e.get("view_only")]
        extract_members(src, [prefix + e["file"] for e in main], TMP / "zip")
        work_dir = TMP / "zip" / prefix
    else:
        work_dir = src
        manifest = json.loads((work_dir / "manifest.json").read_text(encoding="utf-8"))
        main = [e for e in manifest["images"] if not e.get("view_only")]
    table = json.loads(TABLE_PATH.read_text(encoding="utf-8")) if TABLE_PATH.exists() else {}
    log(f"manifest: {len(manifest['images'])} images, {len(main)} main frames; embedded table: {len(table)} frames")
    main = sorted(main, key=lambda e: e["image_id"])
    if SMOKE:
        main = main[:SMOKE]
    CROPS.mkdir(parents=True, exist_ok=True)
    frames, problems = [], []
    for e in main:
        iid = e["image_id"]
        path = work_dir / e["file"]
        with Image.open(path) as im:
            gray = np.asarray(im.convert("L"), dtype=np.uint8)
        H, W = gray.shape
        t = table.get(iid)
        if t is not None:
            vp, ppc, scale_src = [int(v) for v in t["viewport"]], float(t["px_per_cm"]), "embedded_local_manifest"
            if (W, H) != (int(t["width"]), int(t["height"])):
                problems.append(f"{iid}: size {W}x{H} != table {t['width']}x{t['height']}")
            sha = sha256_file(path)
            sha_ok = (sha == t.get("sha256")) if t.get("sha256") else None
            if sha_ok is False:
                problems.append(f"{iid}: PNG sha256 differs from the local copy")
        else:
            vp, ppc, scale_src, sha_ok = [int(v) for v in e["viewport"]], float(e["px_per_cm"]), "zip_manifest", None
            problems.append(f"{iid}: not in the embedded table; using the zip manifest scale (uncorrected?)")
        x1, y1, x2, y2 = max(0, vp[0]), max(0, vp[1]), min(W, vp[2]), min(H, vp[3])
        crop = np.ascontiguousarray(gray[y1:y2, x1:x2])
        Image.fromarray(crop).save(CROPS / f"{iid}.png")
        frames.append(dict(image_id=iid, width=W, height=H, viewport=[x1, y1, x2, y2], px_per_cm=ppc,
                           scale_source=scale_src, sha_ok=sha_ok, crop_w=int(crop.shape[1]), crop_h=int(crop.shape[0]),
                           participant=e.get("participant"), zip_px_per_cm=e.get("px_per_cm"),
                           zip_viewport=e.get("viewport")))
    for p in problems:
        log(f"WARNING {p}")
    write_json(FRAMES, {"source": f"{kind}:{src}", "n": len(frames), "frames": frames, "problems": problems})
    log(f"data: {len(frames)} crops written; sha ok {sum(f['sha_ok'] is True for f in frames)}/{len(frames)}")


