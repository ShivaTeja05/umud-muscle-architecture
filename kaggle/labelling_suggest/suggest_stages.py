def find_files(name: str) -> list[Path]:
    return sorted(p for p in INPUT.rglob(name) if p.is_file())


def _largest_true_run(values: np.ndarray) -> tuple[int, int]:
    """Verbatim from kaggle/infer_maskbank/pipeline.py."""
    padded = np.pad(values.astype(np.int8), 1)
    edges = np.diff(padded)
    starts = np.flatnonzero(edges == 1)
    ends = np.flatnonzero(edges == -1)
    if not len(starts):
        return 0, len(values)
    index = int(np.argmax(ends - starts))
    return int(starts[index]), int(ends[index])


def training_viewport(image: np.ndarray) -> tuple[int, int, int, int]:
    """Verbatim copy of kaggle/aponeurosis_unetpp_384/train.py:training_viewport (via pipeline.py)."""
    gray = image.astype(np.float32)
    vertical_texture = np.abs(np.diff(gray, axis=0)).mean(axis=0)
    left, right = _largest_true_run(vertical_texture > 1.0)
    if right - left < image.shape[1] * 0.35:
        left, right = 0, image.shape[1]
    horizontal_texture = np.abs(np.diff(gray[:, left:right], axis=1)).mean(axis=1)
    top, bottom = _largest_true_run(horizontal_texture > 0.5)
    if bottom - top < image.shape[0] * 0.45:
        top, bottom = 0, image.shape[0]
    return left, top, right, bottom


def to_uint8(probability: np.ndarray) -> np.ndarray:
    return np.clip(np.rint(probability * 255.0), 0, 255).astype(np.uint8)


def all_finite(torch, state: dict) -> tuple[bool, list[str]]:
    bad = [k for k, v in state.items() if hasattr(v, "is_floating_point") and v.is_floating_point()
           and not bool(torch.isfinite(v.float()).all())]
    return not bad, bad


def stage_infer() -> None:
    import cv2
    import warnings

    warnings.filterwarnings("ignore", message=".*autocast.*")
    fo = load_module("fo_src", FO_PATH)
    try:
        smp = fo.ensure_smp()          # pins segmentation-models-pytorch 0.5.0 (pip install if needed)
    except Exception as error:  # noqa: BLE001 - e.g. internet off: fall back to the installed version
        log(f"WARNING ensure_smp failed ({error!r}); using the installed segmentation_models_pytorch")
        import segmentation_models_pytorch as smp
    import torch

    dev = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    info = {"torch": torch.__version__, "smp": smp.__version__, "cv2": cv2.__version__, "device": str(dev),
            "gpu": torch.cuda.get_device_name(0) if dev.type == "cuda" else "", "models": {}, "boxes": {}}
    try:
        import timm
        info["timm"] = timm.__version__
    except Exception:  # noqa: BLE001
        pass
    log(f"torch {torch.__version__} smp {smp.__version__} device {dev} {info['gpu']}")
    frames = read_frames()
    crops = {f["image_id"]: np.asarray(Image.open(CROPS / f"{f['image_id']}.png").convert("L"), dtype=np.uint8)
             for f in frames}
    MAPS.mkdir(parents=True, exist_ok=True)

    # ---- U-Net++ R34 384 (aponeurosis / fascicle fragments): the torch stage of infer_maskbank/pipeline.py
    for key, (filename, slug) in TORCH_MODELS.items():
        hits = find_files(filename)
        log(f"{key}: candidates {[str(p) for p in hits]}")
        pref = [p for p in hits if slug in str(p)] or hits
        if not pref:
            log(f"ERROR {key}: {filename} not found under {INPUT}")
            info["models"][key] = {"error": "not found"}
            continue
        path = pref[0]
        ck = torch.load(path, map_location="cpu", weights_only=False)
        use_vp = bool(ck.get("viewport_preprocessing", False))
        size = int(ck.get("size", 384))
        model = smp.UnetPlusPlus(encoder_name=ck.get("encoder", "resnet34"), encoder_weights=None, in_channels=1,
                                 classes=1, activation=None)
        state = {k.removeprefix("module."): v for k, v in ck["model"].items()}
        ok, bad = all_finite(torch, state)
        model.load_state_dict(state, strict=True)
        model.to(dev).eval()
        info["models"][key] = {"checkpoint": str(path), "sha256": sha256_file(path), "viewport_crop": use_vp,
                               "size": size, "finite": ok, "nonfinite": bad[:10]}
        log(f"{key}: {path} viewport_crop={use_vp} size={size} finite={ok}")
        mean_bank, noflip_bank = {}, {}
        for iid, crop in crops.items():
            h, w = crop.shape
            left, top, right, bottom = training_viewport(crop) if use_vp else (0, 0, w, h)
            info["boxes"].setdefault(iid, {})[key] = [left, top, right, bottom]
            sub = crop[top:bottom, left:right]
            x = cv2.resize(sub, (size, size), interpolation=cv2.INTER_LINEAR).astype(np.float32) / 255.0
            batch = np.ascontiguousarray(np.stack([x, x[:, ::-1]])[:, None])
            with torch.inference_mode():
                prob = torch.sigmoid(model(torch.from_numpy(batch).to(dev))).float().cpu().numpy()[:, 0]
            p0, p1 = prob[0], prob[1][:, ::-1]
            full_mean = np.zeros((h, w), np.float32)
            full_noflip = np.zeros((h, w), np.float32)
            cs = (right - left, bottom - top)
            full_mean[top:bottom, left:right] = cv2.resize(np.ascontiguousarray(0.5 * (p0 + p1)), cs,
                                                           interpolation=cv2.INTER_LINEAR)
            full_noflip[top:bottom, left:right] = cv2.resize(np.ascontiguousarray(p0), cs,
                                                             interpolation=cv2.INTER_LINEAR)
            mean_bank[iid] = to_uint8(full_mean)
            noflip_bank[iid] = to_uint8(full_noflip)
        np.savez_compressed(MAPS / f"{key}.npz", **mean_bank)
        np.savez_compressed(MAPS / f"{key}_noflip.npz", **noflip_bank)
        log(f"{key}: {len(mean_bank)} maps")
        del model, mean_bank, noflip_bank
        if dev.type == "cuda":
            torch.cuda.empty_cache()

    # ---- fasc_orient_v1 (5 folds + hflip TTA), as kaggle/tt_bench/tt_stages.py stage_orient
    hits = sorted(p for p in INPUT.rglob("fold*.pt") if p.is_file())
    log(f"fold*.pt candidates: {[str(p) for p in hits]}")
    cands = [p for p in hits if any(t in str(p) for t in ORIENT_TAGS)]
    by_dir: dict[Path, list[Path]] = {}
    for p in cands:
        by_dir.setdefault(p.parent, []).append(p)
    models, used = [], []
    if by_dir:
        best_dir = max(by_dir, key=lambda d: (len(by_dir[d]), d.name == "checkpoints"))
        for cp in sorted(by_dir[best_dir]):
            st = torch.load(cp, map_location="cpu", weights_only=False)
            sd = {k: (v.float() if v.is_floating_point() else v) for k, v in st["state_dict"].items()}
            ok, bad = all_finite(torch, sd)
            if st.get("encoder") not in (None, fo.ENCODER):
                log(f"WARNING {cp}: encoder {st.get('encoder')} != {fo.ENCODER}; skipped")
                continue
            if not ok:
                log(f"WARNING {cp}: non-finite tensors {bad[:5]}; fold skipped")
                continue
            mdl = fo.build_model(pretrained=False)
            mdl.load_state_dict(sd)
            models.append(mdl.to(dev).eval().to(memory_format=torch.channels_last))
            used.append(str(cp))
    info["models"][ORIENT_MODEL] = {"checkpoints": used, "n_folds": len(models), "size": fo.SIZE,
                                    "encoder": fo.ENCODER}
    log(f"{ORIENT_MODEL}: {len(models)} fold models {used}")
    if models:
        banks = {ch: {} for ch in fo.CHANNELS}
        for iid, crop in crops.items():
            box, kind = fo.viewport(crop, ".png")
            info["boxes"].setdefault(iid, {})[ORIENT_MODEL] = [*box, kind]
            x1, y1, x2, y2 = box
            inp, m = fo.make_input(crop[y1:y2, x1:x2])
            x = fo.to_input(torch.from_numpy(inp[None]).to(dev), torch)
            acc = None
            with torch.no_grad():
                for mdl in models:
                    p, c, s = fo.forward_maps(mdl, x, torch, True)
                    cur = torch.stack([p[0], c[0], s[0]], -1)
                    acc = cur if acc is None else acc + cur
            maps = (acc / len(models)).cpu().numpy().astype(np.float32)
            back = fo.unletterbox(maps, m, x2 - x1, y2 - y1)
            full = np.zeros((crop.shape[0], crop.shape[1], 3), np.float32)
            full[y1:y2, x1:x2] = back
            enc = fo.encode_channels(full[..., 0], full[..., 1], full[..., 2])
            for ch in fo.CHANNELS:
                banks[ch][iid] = enc[ch]
        for ch in fo.CHANNELS:
            np.savez_compressed(MAPS / f"{ORIENT_MODEL}_{ch}.npz", **banks[ch])
        log(f"{ORIENT_MODEL}: {len(crops)} maps")
    write_json(TMP / "run_info_infer.json", info)
    if not models or any("error" in v for v in info["models"].values()):
        log("ERROR: a model is missing (see above); the geometry stage will mark the frames as failed")
        sys.exit(2)


