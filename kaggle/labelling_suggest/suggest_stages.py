def print_input_tree(root: Path, max_depth: int = 5, max_lines: int = 250) -> None:
    """Directories (with file counts) and the first files of each, so the mount layout is in the log."""
    if not root.exists():
        log(f"input root {root} does not exist")
        return
    lines = 0
    for dirpath, dirnames, filenames in os.walk(root):
        depth = len(Path(dirpath).relative_to(root).parts)
        dirnames.sort()
        if depth >= max_depth:
            dirnames[:] = []
        files = sorted(filenames)
        print(f"  [dir] {dirpath}  ({len(files)} files)", flush=True)
        for name in files[:6]:
            p = Path(dirpath) / name
            try:
                size = p.stat().st_size
            except OSError:
                size = -1
            print(f"        {name}  {size / 1e6:.2f} MB", flush=True)
        lines += 1 + min(len(files), 6)
        if lines > max_lines:
            print("  ... (tree truncated)", flush=True)
            return


