class FieldPix:
    """Sampled pixels of the learned orientation field (crop frame, pixel centres at k + 0.5)."""

    def __init__(self, g2, orient, sup, deep, mt_px: float, W: int, H: int, sub: int = FIELD_SUB):
        seg, c2, s2 = g2.orient_maps(orient)
        theta, wmap = g2.field_theta_weight(seg, c2, s2, 1.0)
        ys, xs = np.arange(0, H, sub), np.arange(0, W, sub)
        th = theta[ys][:, xs]
        w = wmap[ys][:, xs]
        X, Y = np.meshgrid(xs + 0.5, ys + 0.5)
        keep = w > 0
        self.g2 = g2
        self.x, self.y, self.th, self.w = X[keep], Y[keep], th[keep].astype(float), w[keep].astype(float)
        above = np.asarray(deep(self.x), float) - self.y           # px above the deep inner edge
        below_sup = self.y - np.asarray(sup(self.x), float)        # px below the superficial inner edge
        self.comp = (below_sup >= COMP_MARGIN * mt_px) & (above >= COMP_MARGIN * mt_px)
        self.strip = (above >= STRIP[0] * mt_px) & (above <= STRIP[1] * mt_px)

    def robust(self, sel: np.ndarray) -> dict:
        return self.g2.robust_axial_mean(self.th[sel], self.w[sel], 8.0)

    def local_angle(self, p0, th0: float, region: np.ndarray, hw: float, iters: int = 5):
        """Robust axial mean of the field in a corridor of half-width hw around the line through p0 at th0,
        re-centred on the new angle until it settles. Returns (theta deg, stats or None, n pixels)."""
        th, st, n = float(th0), None, 0
        for _ in range(iters):
            r = math.radians(th)
            dist = np.abs(-(self.x - p0[0]) * math.sin(r) + (self.y - p0[1]) * math.cos(r))
            sel = region & (dist <= hw)
            k = int(sel.sum())
            if k < MIN_PX:
                break
            s = self.robust(sel)
            if s["mean"] is None or not np.isfinite(s["mean"]):
                break
            st, n = s, k
            new = float(self.g2.wrap90(s["mean"]))
            delta = float(self.g2.wrap90(new - th))
            th = new
            if abs(delta) < 0.05:
                break
        return th, st, n


def up_dir(th_deg: float) -> np.ndarray:
    """Unit vector of the axial angle th pointing up the image (from the deep toward the superficial band)."""
    r = math.radians(th_deg)
    d = np.array([math.cos(r), math.sin(r)])
    return -d if d[1] > 0 else d


def tangent_deg(curve, x: float) -> float:
    return float(math.degrees(math.atan(float(curve.slope(x)))))


def rel_to_deep(g2, th: float, deep, x: float) -> float:
    return abs(float(g2.wrap90(th - tangent_deg(deep, x))))


def hit_sup(g2, sup, p, d, W: int):
    """Intersection of the line through p (direction d) with the superficial curve, above p."""
    if abs(d[0]) < 1e-6:
        return float(p[0]), float(sup(p[0]))
    vx, vy = (d[0], d[1]) if d[0] > 0 else (-d[0], -d[1])
    fr = dict(cx=float(p[0]), cy=float(p[1]) - 1e-3, vx=float(vx), vy=float(vy))
    return g2._line_curve_x(fr, sup, np.linspace(-3 * W, 4 * W, 6001), "sup")


def clip_params(p, q, W: float, H: float) -> tuple[float, float] | None:
    """Liang-Barsky: parameter range [t0, t1] of segment p->q inside [0, W] x [0, H] (None if outside)."""
    t0, t1 = 0.0, 1.0
    dx, dy = q[0] - p[0], q[1] - p[1]
    for pk, qk in ((-dx, p[0]), (dx, W - p[0]), (-dy, p[1]), (dy, H - p[1])):
        if abs(pk) < 1e-12:
            if qk < 0:
                return None
            continue
        t = qk / pk
        if pk < 0:
            t0 = max(t0, t)
        else:
            t1 = min(t1, t)
        if t0 > t1:
            return None
    return t0, t1


def rpt(p, off) -> list[float]:
    return [round(float(p[0]) + off[0], 2), round(float(p[1]) + off[1], 2)]


def angle_between(p0, p1, q0, q1) -> float:
    """tools/annotator/labels.py angle_between (the annotator's PA formula)."""
    a = math.atan2(p1[1] - p0[1], p1[0] - p0[0])
    b = math.atan2(q1[1] - q0[1], q1[0] - q0[0])
    d = math.degrees(abs(a - b)) % 180.0
    return 180.0 - d if d > 90.0 else d


def refine_superficial(g2, A, crop, cfg, res) -> tuple[dict, dict]:
    """Protocol guard for the superficial inner edge (suggestions only; the pipeline values are untouched).

    select_pair skips a band closer than pair_min_sep * H below the superficial candidate, so with a thin skin /
    fascia line right above the aponeurosis the pair can become (skin line, deep band) and the superficial inner edge
    the skin line's lower edge. When the chosen superficial band i has, between it and the deep band j, a band k that
    is that close below i (no muscle in between), at least half as wide as the field and parallel to i (<= 5 deg),
    the lowest such k is the superficial aponeurosis: its lower edge becomes the superficial inner edge.
    Returns (curves dict for suggest_lines, info)."""
    cv = dict(res.curves)
    info = {"sup_refined": False}
    pair = res.diag.get("pair")
    if res.diag.get("apo_source") != "primary" or not pair:
        return cv, info
    i, j = (int(v) for v in str(pair).split(","))
    H, W = crop.shape
    vx0, vx1 = g2.estimate_viewport_x(crop)
    wref = float(max(vx1 - vx0, 0.1 * W))
    bands = g2.extract_bands(g2.as_prob(A), cfg, wref)
    if len(bands) <= max(i, j) or j - i < 2:
        return cv, info
    ks = []
    for k in range(i + 1, j):
        st_ik = g2._pair_stats(bands[i], bands[k], int(wref))
        st_kj = g2._pair_stats(bands[k], bands[j], int(wref))
        if (st_ik["sep"] < cfg.pair_min_sep * H and bands[k].span >= 0.5 * wref and st_ik["dang"] <= 5.0
                and st_kj["sep"] >= cfg.pair_min_sep * H and st_kj["min_gap"] >= 0):
            ks.append(k)
    if not ks:
        return cv, info
    k = max(ks)
    b = bands[k]
    sup = g2.EdgeCurve(b.x + 0.5, b.bot, cfg.edge_fit, cfg.edge_extrap, cfg.savgol_frac, cfg.edge_end_frac)
    deep = cv["deep_curve"]
    s_lo, s_hi = max(sup.x0, deep.x0), min(sup.x1, deep.x1)
    if s_hi <= s_lo:
        return cv, info
    xs = s_lo + (s_hi - s_lo) * np.asarray(MT_FRACS)
    mt_px = float(np.mean(deep(xs) - sup(xs)))
    if not mt_px > 0:
        return cv, info
    old = cv["sup_curve"]
    cv.update(sup_curve=sup, s_lo=s_lo, s_hi=s_hi, mt_px=mt_px)
    info = {"sup_refined": True, "sup_band_from": i, "sup_band_to": k,
            "sup_shift_px": float(np.mean(sup(xs) - old(xs)))}
    return cv, info


def suggest_lines(g2, res, orient, W: int, H: int, ppc: float, off: tuple[float, float],
                  curves: dict | None = None) -> dict:
    """The 3 MT / 3 FL / 3 PA suggestion lines and the two inner-edge polylines (see the module docstring)."""
    cv = curves or res.curves
    sup, deep = cv["sup_curve"], cv["deep_curve"]
    mt_px, s_lo, s_hi = float(cv["mt_px"]), float(cv["s_lo"]), float(cv["s_hi"])
    px_mm = ppc / 10.0
    mm = 10.0 / ppc
    fp = FieldPix(g2, orient, sup, deep, mt_px, W, H)
    lo, hi = s_lo + 0.1 * (s_hi - s_lo), s_hi - 0.1 * (s_hi - s_lo)
    inx = (fp.x >= lo) & (fp.x <= hi)
    st_g = fp.robust(fp.comp & inx) if (fp.comp & inx).sum() >= MIN_PX else None
    st_s = fp.robust(fp.strip & inx) if (fp.strip & inx).sum() >= MIN_PX else None
    th_g = st_g["mean"] if st_g and np.isfinite(st_g["mean"]) else float("nan")
    th_s = st_s["mean"] if st_s and np.isfinite(st_s["mean"]) else th_g
    diag = dict(theta_comp=th_g, theta_strip=th_s, comp_conc=st_g["conc"] if st_g else None,
                strip_conc=st_s["conc"] if st_s else None, n_field_px=int(fp.x.size))
    if not np.isfinite(th_g) or not (MIN_REL_DEG <= rel_to_deep(g2, th_g, deep, 0.5 * (s_lo + s_hi)) <= MAX_REL_DEG):
        raise ValueError(f"no usable fascicle orientation in the compartment (theta {th_g})")

    out = {"mt": [], "fl": [], "pa": []}
    vals = {"mt_mm": [], "fl_mm": [], "pa_deg": [], "fl_extrap_frac": []}
    concs, local = [], {"fl": [], "pa": []}

    # ---- MT: vertical, at the annotator guides (fractions of the viewport = crop width)
    for f in MT_FRACS:
        x = f * W
        ys, yd = float(sup(x)), float(deep(x))
        if not (yd > ys):
            raise ValueError(f"inner edges cross at x={x:.1f}")
        out["mt"].append([rpt((x, ys), off), rpt((x, yd), off)])
        vals["mt_mm"].append((yd - ys) * mm)

    # ---- FL: straight fascicle, local field orientation along it, midpoint (or insertion) at f * W
    hw_fl = max(FL_CORRIDOR[0] * mt_px, FL_CORRIDOR[1] * px_mm)
    for f in FL_FRACS:
        xm = f * W
        th = th_g
        d = up_dir(th)
        xi = xm - (0.5 * mt_px / max(abs(d[1]), 1e-3) * d[0] if FL_ANCHOR == "midpoint" else 0.0)
        st, n, q = None, 0, None
        for _ in range(6):
            p = (xi, float(deep(xi)))
            d = up_dir(th)
            q = hit_sup(g2, sup, p, d, W)
            if q is None:
                break
            mid = (0.5 * (p[0] + q[0]), 0.5 * (p[1] + q[1]))
            th_new, st_new, n_new = fp.local_angle(mid, th, fp.comp, hw_fl)
            if st_new is not None and MIN_REL_DEG <= rel_to_deep(g2, th_new, deep, xi) <= MAX_REL_DEG:
                th, st, n = th_new, st_new, n_new
            if FL_ANCHOR == "midpoint":
                xi += xm - mid[0]
        p = (xi, float(deep(xi)))
        d = up_dir(th)
        q = hit_sup(g2, sup, p, d, W)
        if q is None:
            raise ValueError(f"FL line at {f:.2f} never meets the superficial band")
        line = [p]
        tt = clip_params(p, q, float(W), float(H))
        L = math.hypot(q[0] - p[0], q[1] - p[1])
        inside = (tt[1] - tt[0]) if tt else 0.0
        if tt:
            for t in tt:
                if 1.0 < t * L < L - 1.0:    # the image border crossing, > 1 px from both ends
                    line.append((p[0] + t * (q[0] - p[0]), p[1] + t * (q[1] - p[1])))
        line.append(q)
        out["fl"].append([rpt(pt, off) for pt in line])
        vals["fl_mm"].append(L * mm)
        vals["fl_extrap_frac"].append(1.0 - inside)
        local["fl"].append(dict(theta=th, n=n, conc=st["conc"] if st else None, local=st is not None))
        concs.append(st["conc"] if st else 0.5 * (diag["comp_conc"] or 0.0))

    # ---- PA: insertion on the deep band, local deep-strip orientation, deep tangent +- 5 mm
    hw_pa = max(PA_CORRIDOR[0] * mt_px, PA_CORRIDOR[1] * px_mm)
    for f in PA_FRACS:
        xi = f * W
        p = (xi, float(deep(xi)))
        th0 = th_s if np.isfinite(th_s) else th_g
        th, st, n = fp.local_angle(p, th0, fp.strip, hw_pa)
        if st is None or not (MIN_REL_DEG <= rel_to_deep(g2, th, deep, xi) <= MAX_REL_DEG):
            th, st, n = th0, None, 0
        d = up_dir(th)
        rel = rel_to_deep(g2, th, deep, xi)
        far = min(PA_FAR_MM * px_mm, PA_FAR_MAX_MT * mt_px / max(math.sin(math.radians(rel)), 0.05))
        f0 = (p[0] + d[0] * PA_NEAR_MM * px_mm, p[1] + d[1] * PA_NEAR_MM * px_mm)
        f1 = (p[0] + d[0] * far, p[1] + d[1] * far)
        s = float(deep.slope(xi))
        tvec = np.array([1.0, s]) / math.hypot(1.0, s)
        a0 = (p[0] - tvec[0] * PA_APO_HALF_MM * px_mm, p[1] - tvec[1] * PA_APO_HALF_MM * px_mm)
        a1 = (p[0] + tvec[0] * PA_APO_HALF_MM * px_mm, p[1] + tvec[1] * PA_APO_HALF_MM * px_mm)
        out["pa"].append([rpt(f0, off), rpt(f1, off), rpt(a0, off), rpt(a1, off)])
        vals["pa_deg"].append(angle_between(f0, f1, a0, a1))
        local["pa"].append(dict(theta=th, n=n, conc=st["conc"] if st else None, local=st is not None))
        concs.append(st["conc"] if st else 0.5 * (diag["strip_conc"] or 0.0))

    xs = np.linspace(0.0, float(W), N_APO_PTS)
    out["apo_sup"] = [rpt((x, float(sup(x))), off) for x in xs]
    out["apo_deep"] = [rpt((x, float(deep(x))), off) for x in xs]
    diag["local"] = local
    diag["orient_conc_mean"] = float(np.mean([c for c in concs if c is not None])) if concs else 0.0
    return dict(prefill=out, values=vals, diag=diag)


def confidence(res, res_tta, sug: dict) -> tuple[float, dict]:
    v = sug["values"]
    c_geo = float(res.confidence) if np.isfinite(res.confidence) else 0.0
    c_mt = float(res.variants.get("mt_conf", 0.0) or 0.0)
    c_or = float(np.clip(sug["diag"].get("orient_conc_mean") or 0.0, 0.0, 1.0))
    mt_a = float(res.mt_mm)       # the same pipeline MT on the noflip map and on the hflip-TTA map
    mt_b = float(res_tta.mt_mm) if res_tta is not None and np.isfinite(res_tta.mt_mm) else float("nan")
    c_tta = math.exp(-abs(mt_a - mt_b) / 1.0) if np.isfinite(mt_b) and np.isfinite(mt_a) else 0.5
    means = {"mt": float(np.mean(v["mt_mm"])), "pa": float(np.mean(v["pa_deg"])), "fl": float(np.mean(v["fl_mm"]))}
    rng = 1.0
    for k, (a, b) in RANGES.items():
        if not (a <= means[k] <= b):
            rng *= 0.6
    parts = [max(c, 1e-3) for c in (c_geo, c_mt, c_or, c_tta)]
    conf = float(np.clip(np.prod(parts) ** 0.25 * rng, 0.0, 1.0))
    return round(conf, 3), dict(geo=c_geo, mt=c_mt, orient=c_or, tta=c_tta, range=rng, mt_tta_mm=mt_b)


def geometry_cfg(g2):
    """scripts/eval_apo_v2.make_cfg("v2e", 0.8, edges=False).with_(fasc_thr=0.95): the "ours" apo source."""
    return g2.recommended_config(apo_thr=0.8, fasc_thr=0.95, compute_streamline=False, edge_extrap="end_linear",
                                 edge_source="mask")


class Maps:
    def __init__(self, root: Path):
        self.root = root
        self.open: dict[str, np.lib.npyio.NpzFile] = {}

    def get(self, model: str, iid: str):
        if model not in self.open:
            p = self.root / f"{model}.npz"
            if not p.exists():
                return None
            self.open[model] = np.load(p, allow_pickle=False)
        f = self.open[model]
        return f[iid] if iid in f.files else None


def measure_frame(g2, maps: Maps, fr: dict) -> dict:
    iid = fr["image_id"]
    crop = np.asarray(Image.open(CROPS / f"{iid}.png").convert("L"), dtype=np.uint8)
    H, W = crop.shape
    A, Am, F = (maps.get(m, iid) for m in ("ours_apo384_noflip", "ours_apo384", "ours_fasc384_noflip"))
    seg, c2, s2 = (maps.get(f"{ORIENT_MODEL}_{c}", iid) for c in ("seg", "cos2", "sin2"))
    if A is None or F is None or c2 is None or s2 is None or seg is None:
        return dict(ok=False, reason="missing_maps")
    orient = (g2.as_prob(seg), g2.decode_orient(c2), g2.decode_orient(s2))
    cfg = geometry_cfg(g2)
    fbs = [("tta", Am, 0.8), ("tta_lo", Am, 0.5)] if Am is not None else []
    res = g2.measure_apo(A, F, crop, fr["px_per_cm"], cfg, fallbacks=fbs, keep_details=True, orient=orient)
    diag = {k: res.diag.get(k) for k in ("apo_source", "n_bands", "n_bands_primary", "pair", "pair_fallback",
                                         "shared_frac", "deep_angle", "sup_angle", "n_frag", "fail")}
    diag["flags"] = list(res.flags)
    if not res.curves or not np.isfinite(res.mt_mm):
        return dict(ok=False, reason=f"geometry: {res.diag.get('fail', 'no curves')}", diag=diag)
    fa = g2.field_architecture(res, orient, g2.FieldConfig(), cfg.pa_reference)
    res.variants.update(fa["variants"])
    res.diag.update(fa["diag"])
    res_tta = None
    if Am is not None:
        res_tta = g2.measure_apo(Am, F, crop, fr["px_per_cm"], cfg.with_(compute_structure=False))
    off = (float(fr["viewport"][0]), float(fr["viewport"][1]))
    curves, ref_info = refine_superficial(g2, A, crop, cfg, res)
    diag.update(ref_info)
    sug = suggest_lines(g2, res, orient, W, H, float(fr["px_per_cm"]), off, curves)
    conf, parts = confidence(res, res_tta, sug)
    sug["prefill"]["confidence"] = conf
    v = res.variants
    pf, pfd, pins = v.get("pa_fusion"), v.get("pa_fd_strip"), v.get("pa_fd_ins")
    g0 = pfd if (pins is not None and pf is not None and np.isfinite(pins) and np.isfinite(pf) and pins - pf > 0
                 and pfd is not None and np.isfinite(pfd)) else pf
    sug["values"].update(
        mt_mean=float(np.mean(sug["values"]["mt_mm"])), fl_mean=float(np.mean(sug["values"]["fl_mm"])),
        pa_mean=float(np.mean(sug["values"]["pa_deg"])),
        pipeline=dict(mt_mm=res.mt_mm, mt_lin=v.get("mt_lin"), pa_fusion=pf, pa_fd_strip=pfd, pa_fd_ins=pins,
                      pa_g0=g0, fl_ensemble=res.fl_mm, fl_cfd=v.get("fl_cfd"), fl_straight=v.get("fl_straight")))
    diag.update(sug["diag"])
    diag["conf_parts"] = parts
    diag["viewport"] = fr["viewport"]
    diag["px_per_cm"] = fr["px_per_cm"]
    return dict(ok=True, prefill=sug["prefill"], values=sug["values"], diag=diag)


def draw_preview(fr: dict, entry: dict, path: Path) -> int:
    """Viewport crop on a padded canvas (so the extrapolated FL ends show), lines drawn, PNG; returns bytes."""
    import cv2

    crop = np.asarray(Image.open(CROPS / f"{fr['image_id']}.png").convert("L"), dtype=np.uint8)
    H, W = crop.shape
    pad_x, pad_y = int(0.45 * W), int(0.10 * H)
    canvas = np.full((H + 2 * pad_y, W + 2 * pad_x, 3), 40, np.uint8)
    canvas[pad_y:pad_y + H, pad_x:pad_x + W] = crop[..., None]
    ox, oy = fr["viewport"][0] - pad_x, fr["viewport"][1] - pad_y
    sc = 4  # sub-pixel drawing shift

    def pts(seq):
        return np.array([[int(round((x - ox) * (1 << sc))), int(round((y - oy) * (1 << sc)))] for x, y in seq],
                        np.int32)

    pf = entry["prefill"]
    colors = {"apo": (255, 255, 0), "mt": (0, 230, 255), "fl": (60, 220, 60), "pa_f": (255, 80, 255),
              "pa_a": (0, 140, 255)}
    for key in ("apo_sup", "apo_deep"):
        cv2.polylines(canvas, [pts(pf[key])], False, colors["apo"], 1, cv2.LINE_AA, sc)
    for m in pf["mt"]:
        cv2.polylines(canvas, [pts(m)], False, colors["mt"], 2, cv2.LINE_AA, sc)
    for m in pf["fl"]:
        cv2.polylines(canvas, [pts(m)], False, colors["fl"], 2, cv2.LINE_AA, sc)
    for m in pf["pa"]:
        cv2.polylines(canvas, [pts(m[:2])], False, colors["pa_f"], 2, cv2.LINE_AA, sc)
        cv2.polylines(canvas, [pts(m[2:])], False, colors["pa_a"], 2, cv2.LINE_AA, sc)
    cv2.rectangle(canvas, (pad_x, pad_y), (pad_x + W - 1, pad_y + H - 1), (120, 120, 120), 1)
    v = entry["values"]
    text = (f"{fr['image_id']}  MT {v['mt_mean']:.1f} mm  FL {v['fl_mean']:.1f} mm  PA {v['pa_mean']:.1f} deg  "
            f"conf {pf['confidence']:.2f}")
    s = min(1.0, PREVIEW_MAX_W / canvas.shape[1])
    small = cv2.resize(canvas, (int(canvas.shape[1] * s), int(canvas.shape[0] * s)), interpolation=cv2.INTER_AREA)
    cv2.putText(small, text, (6, 16), cv2.FONT_HERSHEY_SIMPLEX, 0.42, (255, 255, 255), 1, cv2.LINE_AA)
    path.parent.mkdir(parents=True, exist_ok=True)
    cv2.imwrite(str(path), cv2.cvtColor(small, cv2.COLOR_RGB2BGR), [cv2.IMWRITE_PNG_COMPRESSION, 9])
    return path.stat().st_size


