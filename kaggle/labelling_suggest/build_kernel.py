"""Generate kernel.py + kernel-metadata.json for shivateja005/umud-labelling-suggest (never pushes).

kernel.py embeds (zlib + base64) three sources, unchanged:
  geometry_v2.py   = src/umud/geometry_v2.py               (inner edges, pair selection, field PA / FL)
  fo_src.py        = kaggle/fasc_orient_v1/train.py         (fasc_orient_v1 model, viewport, letterbox, TTA, encoding)
  suggest_stages.py = kaggle/labelling_suggest/suggest_stages.py (data / infer / geometry stages)
plus the per-frame table of the 96 main WRK frames read from the LOCAL work manifest (the one the labeller uses):
size, corrected viewport and px_per_cm, participant and the PNG sha256. The zip on Kaggle still carries the
uncorrected kernel scale, so the kernel must not trust it.

  .venv/bin/python kaggle/labelling_suggest/build_kernel.py            # full run
  .venv/bin/python kaggle/labelling_suggest/build_kernel.py --smoke 4  # first 4 frames only
  .venv/bin/python kaggle/labelling_suggest/build_kernel.py --save-maps  # also keep the maps (~40 MB)

Push (Claude, after review):  .venv/bin/kaggle kernels push -p kaggle/labelling_suggest --accelerator NvidiaTeslaT4
Fetch only the small outputs:  .venv/bin/kaggle kernels output shivateja005/umud-labelling-suggest
    -p artifacts/labelling_suggest_out --force --file-pattern "(suggestions_v1\\.json|previews/.*|run_info\\.json|logs/.*)"
Then:  .venv/bin/python tools/annotator/apply_prefill.py --suggestions artifacts/labelling_suggest_out/suggestions_v1.json
GPL-3.0-only.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
SOURCES = {"geometry_v2.py": REPO / "src/umud/geometry_v2.py",
           "fo_src.py": REPO / "kaggle/fasc_orient_v1/train.py",
           "suggest_stages.py": HERE / "suggest_stages.py"}
WORK_MANIFEST = REPO / "data/manual_labelling/work/manifest.json"
KERNEL_SOURCES = ["shivateja005/umud-u-net-aponeurosis-384-cli", "shivateja005/umud-u-net-fascicle-384-cli",
                  "shivateja005/umud-fasc-orient-v1", "shivateja005/umud-labelling-frames"]

LAUNCHER = '''"""UMUD labelling suggestions launcher (generated by kaggle/labelling_suggest/build_kernel.py). GPL-3.0-only.

Stages data -> infer -> geometry of suggest_stages.py, each in its own subprocess (see that file's docstring).
No competition data is attached or read. Outputs: /kaggle/working/suggestions_v1.json, previews/, logs/, run_info.json.
"""
import base64, json, os, subprocess, sys, time, zlib
from pathlib import Path

SMOKE = {smoke}
SAVE_MAPS = {save_maps}
SOURCE_SHA256 = {source_sha}
TABLE = {table}
SOURCES = {payload}
TMP = Path("/tmp/suggest")
OUT = Path("/kaggle/working")
T0 = time.time()


def say(msg):
    print(f"[launcher {{time.time() - T0:7.1f}}s] {{msg}}", flush=True)


def run(stage):
    env = dict(os.environ, SUGGEST_SMOKE=str(SMOKE), SUGGEST_SAVE_MAPS="1" if SAVE_MAPS else "0",
               SUGGEST_TMP=str(TMP), SUGGEST_OUT=str(OUT), PYTHONUNBUFFERED="1")
    (OUT / "logs").mkdir(parents=True, exist_ok=True)
    t = time.time()
    with (OUT / "logs" / f"{{stage}}.log").open("w", encoding="utf-8") as lf:
        p = subprocess.Popen([sys.executable, "-u", str(TMP / "suggest_stages.py"), "--stage", stage], cwd=str(TMP),
                             stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, env=env)
        for line in p.stdout:
            print(f"[{{stage}}] {{line}}", end="", flush=True)
            lf.write(line)
        code = p.wait()
    say(f"stage {{stage}} exit={{code}} {{time.time() - t:.0f}}s")
    return code


def main():
    TMP.mkdir(parents=True, exist_ok=True)
    OUT.mkdir(parents=True, exist_ok=True)
    for name, blob in SOURCES.items():
        (TMP / name).write_text(zlib.decompress(base64.b64decode(blob)).decode("utf-8"), encoding="utf-8")
    (TMP / "frames_table.json").write_text(json.dumps(TABLE), encoding="utf-8")
    say(f"python={{sys.version.split()[0]}} cpus={{os.cpu_count()}} smoke={{SMOKE}} save_maps={{SAVE_MAPS}} "
        f"frames in table={{len(TABLE)}}")
    try:
        subprocess.run(["nvidia-smi", "--query-gpu=name,memory.total,driver_version", "--format=csv"], check=False)
    except OSError as error:
        say(f"nvidia-smi unavailable ({{error!r}}); the infer stage falls back to the CPU")
    codes = {{"data": run("data")}}
    if codes["data"] == 0:
        codes["infer"] = run("infer")
        codes["geometry"] = run("geometry")   # always: failed frames are recorded with their reason
    (OUT / "run_info.json").write_text(json.dumps({{"exit_codes": codes, "source_sha256": SOURCE_SHA256,
                                                    "smoke": SMOKE, "save_maps": SAVE_MAPS}}, indent=1))
    say(f"exit codes {{codes}}")
    for p in sorted(OUT.rglob("*")):
        if p.is_file():
            say(f"  {{p.relative_to(OUT)}} {{p.stat().st_size / 1e6:.3f}} MB")


main()
'''


def sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def frames_table() -> dict:
    """Per main frame of the local work manifest: size, viewport, px_per_cm, participant, PNG sha256."""
    man = json.loads(WORK_MANIFEST.read_text(encoding="utf-8"))
    out = {}
    for e in man["images"]:
        if e.get("view_only"):
            continue
        png = WORK_MANIFEST.parent / e["file"]
        out[e["image_id"]] = {"width": int(e["width"]), "height": int(e["height"]),
                              "viewport": [int(v) for v in e["viewport"]], "px_per_cm": float(e["px_per_cm"]),
                              "participant": e.get("participant"), "sha256": sha256_bytes(png.read_bytes())}
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", type=int, default=0, help="only the first N frames (0 = all)")
    ap.add_argument("--save-maps", action="store_true", help="also write the maps to /kaggle/working/maps (~40 MB)")
    args = ap.parse_args()
    texts = {name: p.read_text(encoding="utf-8") for name, p in SOURCES.items()}
    payload = {name: base64.b64encode(zlib.compress(t.encode("utf-8"), 9)).decode("ascii") for name, t in texts.items()}
    source_sha = {name: sha256_bytes(t.encode("utf-8")) for name, t in texts.items()}
    table = frames_table()
    pp = sorted({v["participant"] for v in table.values()})
    print(f"table: {len(table)} main frames, participants {pp}, "
          f"px_per_cm {sorted({v['px_per_cm'] for v in table.values()})}, "
          f"viewports {sorted({tuple(v['viewport']) for v in table.values()})}")
    code = LAUNCHER.format(smoke=int(args.smoke), save_maps=bool(args.save_maps), source_sha=repr(source_sha),
                           table=repr(dict(sorted(table.items()))), payload=json.dumps(payload, indent=0))
    compile(code, "kernel.py", "exec")
    (HERE / "kernel.py").write_text(code, encoding="utf-8")
    meta = {"id": "shivateja005/umud-labelling-suggest", "title": "UMUD Labelling Suggest", "code_file": "kernel.py",
            "language": "python", "kernel_type": "script", "is_private": "true", "enable_gpu": "true",
            "enable_tpu": "false", "enable_internet": "true", "machine_shape": "NvidiaTeslaT4",
            "competition_sources": [], "dataset_sources": [], "kernel_sources": KERNEL_SOURCES, "model_sources": []}
    (HERE / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    print(f"wrote kernel.py ({(HERE / 'kernel.py').stat().st_size / 1e3:.0f} kB), kernel-metadata.json; "
          f"sources {source_sha}")


if __name__ == "__main__":
    main()
