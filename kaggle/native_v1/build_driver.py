"""Build the Kaggle kernel folders of the native-geometry retrain (fasc_nat + apo_nat in ONE GPU session).

    .venv/bin/python kaggle/native_v1/build_driver.py

writes
    kaggle/native_v1/kernel/{run.py,kernel-metadata.json}    shivateja005/umud-native-v1           (T4 x2, full)
    kaggle/native_v1/cpusmoke/{run.py,kernel-metadata.json}  shivateja005/umud-native-v1-cpusmoke  (CPU, tiny)

run.py embeds (zlib + base64, sha256-checked) kaggle/fasc_nat/train.py, kaggle/apo_nat/train.py and the parent
runs' fold files (artifacts/kaggle/fasc_orient_v1/metrics/folds.csv, artifacts/kaggle/apo_v2/apo_v2/folds.csv,
reduced to the id/group/fold columns), writes them to /kaggle/working/native_v1_src and runs phase 1 (fasc_nat)
then phase 2 (apo_nat) as subprocesses; both phases use both GPUs. Outputs (all under /kaggle/working):
    maskbank/{test,static,dynamic,vl,train_oof}__fasc_nat_{seg,cos2,sin2}.npz, ...__apo_nat_{band,upper,lower}.npz,
    maskbank/manifest.csv (+ manifest_<model>.csv, <model>_viewports.csv), fasc_nat/ (checkpoints, metrics,
    logs, viz), apo_nat/ (ckpt, fold metrics, config, log), native_v1_summary.json.
"""
from __future__ import annotations

import base64
import csv
import hashlib
import io
import json
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
SOURCES = {
    "fasc_nat.py": ROOT / "kaggle/fasc_nat/train.py",
    "apo_nat.py": ROOT / "kaggle/apo_nat/train.py",
}
FOLDS = {
    "fasc_orient_v1_folds.csv": (ROOT / "artifacts/kaggle/fasc_orient_v1/metrics/folds.csv",
                                 ["stem", "representative", "group", "fold"]),
    "apo_v2_folds.csv": (ROOT / "artifacts/kaggle/apo_v2/apo_v2/folds.csv", ["image_id", "group", "fold"]),
}
KERNELS = {
    "kernel": {"mode": "full", "id": "shivateja005/umud-native-v1", "title": "UMUD Native V1", "gpu": True},
    "cpusmoke": {"mode": "cpusmoke", "id": "shivateja005/umud-native-v1-cpusmoke",
                 "title": "UMUD Native V1 Cpusmoke", "gpu": False},
}

TEMPLATE = r'''"""UMUD native-geometry retrain: fasc_nat (phase 1) + apo_nat (phase 2) in one Kaggle session.

GENERATED by kaggle/native_v1/build_driver.py - do not edit; edit kaggle/fasc_nat/train.py, kaggle/apo_nat/train.py.
The phase scripts and the reference folds of fasc_orient_v1 / apo_v2 are embedded below (zlib+base64) and
checked against their sha256 before use:
@@SHA_LINES@@
"""
import base64
import csv
import hashlib
import json
import os
import subprocess
import sys
import time
import zlib
from pathlib import Path

MODE = "@@MODE@@"
PHASES = ["fasc_nat", "apo_nat"]
SHA256 = @@SHA@@
BLOBS = @@BLOBS@@
WORK = Path("/kaggle/working")


def main():
    t0 = time.time()
    src = WORK / "native_v1_src"
    src.mkdir(parents=True, exist_ok=True)
    for name, blob in BLOBS.items():
        data = zlib.decompress(base64.b64decode(blob))
        if hashlib.sha256(data).hexdigest() != SHA256[name]:
            raise RuntimeError(f"sha256 mismatch for {name}")
        (src / name).write_bytes(data)
    env = dict(os.environ, UMUD_MODE=MODE, PYTHONUNBUFFERED="1",
               UMUD_FASC_FOLDS=str(src / "fasc_orient_v1_folds.csv"), UMUD_APO_FOLDS=str(src / "apo_v2_folds.csv"))
    print(f"[driver] MODE={MODE} phases={PHASES} sources={json.dumps(SHA256)}", flush=True)
    results = {}
    for ph in PHASES:
        t = time.time()
        print(f"[driver] ===== phase {ph} start (t={(t - t0) / 60:.1f} min)", flush=True)
        p = subprocess.Popen([sys.executable, "-u", str(src / f"{ph}.py")], env=env, stdout=subprocess.PIPE,
                             stderr=subprocess.STDOUT)
        for raw in iter(p.stdout.readline, b""):
            sys.stdout.write(f"[{ph}] " + raw.decode("utf-8", "replace"))
            sys.stdout.flush()
        rc = p.wait()
        results[ph] = {"exit_code": rc, "minutes": round((time.time() - t) / 60, 2)}
        print(f"[driver] ===== phase {ph} finished exit={rc} in {(time.time() - t) / 60:.1f} min", flush=True)
    # merged manifest of the shared evaluation sets (train_oof differs per model: see manifest_<model>.csv)
    bank = WORK / "maskbank"
    rows, seen = [], set()
    for ph in PHASES:
        mf = bank / f"manifest_{ph}.csv"
        if not mf.exists():
            continue
        with open(mf, newline="") as fh:
            for r in csv.DictReader(fh):
                key = (r["dataset"], r["image_id"], r["source_filename"], r["height"], r["width"])
                if r["dataset"] != "train_oof" and key not in seen:
                    seen.add(key)
                    rows.append(key)
    if rows:
        with open(bank / "manifest.csv", "w", newline="") as fh:
            w = csv.writer(fh)
            w.writerow(["dataset", "image_id", "source_filename", "height", "width"])
            w.writerows(rows)
    files = sorted(str(p.relative_to(WORK)) for p in bank.glob("*")) if bank.exists() else []
    summary = {"mode": MODE, "phases": results, "total_minutes": round((time.time() - t0) / 60, 2),
               "sources_sha256": SHA256, "maskbank_files": files}
    (WORK / "native_v1_summary.json").write_text(json.dumps(summary, indent=2))
    print(f"[driver] DONE {json.dumps(summary)}", flush=True)
    if MODE != "full" and any(v["exit_code"] != 0 for v in results.values()):
        sys.exit(1)


if __name__ == "__main__":
    main()
'''


def reduced_csv(path: Path, cols: list[str]) -> bytes:
    with open(path, newline="") as fh:
        rows = list(csv.DictReader(fh))
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(cols)
    for r in rows:
        w.writerow([r[c] for c in cols])
    return buf.getvalue().encode()


def main() -> None:
    payload = {name: p.read_bytes() for name, p in SOURCES.items()}
    for name, (p, cols) in FOLDS.items():
        payload[name] = reduced_csv(p, cols)
    sha = {k: hashlib.sha256(v).hexdigest() for k, v in payload.items()}
    blobs = {k: base64.b64encode(zlib.compress(v, 9)).decode() for k, v in payload.items()}
    sha_lines = "\n".join(f"    {k}: {v}" for k, v in sha.items())
    for sub, cfg in KERNELS.items():
        out = HERE / sub
        out.mkdir(parents=True, exist_ok=True)
        code = (TEMPLATE.replace("@@SHA_LINES@@", sha_lines).replace("@@MODE@@", cfg["mode"])
                .replace("@@SHA@@", json.dumps(sha, indent=4)).replace("@@BLOBS@@", json.dumps(blobs, indent=4)))
        (out / "run.py").write_text(code)
        meta = {
            "id": cfg["id"], "title": cfg["title"], "code_file": "run.py", "language": "python",
            "kernel_type": "script", "is_private": "true", "enable_gpu": "true" if cfg["gpu"] else "false",
            "enable_tpu": "false", "enable_internet": "true",
            "competition_sources": ["umud-challenge-muscle-architecture-in-ultrasound-data"],
            "dataset_sources": [], "kernel_sources": [], "model_sources": [],
        }
        if cfg["gpu"]:
            meta["machine_shape"] = "NvidiaTeslaT4"
        (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
        print(f"{out / 'run.py'}: {len(code) / 1024:.0f} KiB mode={cfg['mode']} id={cfg['id']}")
    for k, v in sha.items():
        print(f"  {k} {len(payload[k])} B sha256={v[:16]}")


if __name__ == "__main__":
    main()
